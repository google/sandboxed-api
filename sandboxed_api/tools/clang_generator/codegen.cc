// Helper to retrieve the return type of a callback parameter.
std::string GetCallbackReturnType(const ir::CallbackParam& cb) {
  return cb.return_value != nullptr ? cb.return_value->type.canonical_name
                                    : "void";
}

// Returns true if the callback returns a pointer.
bool CallbackReturnsPointer(const ir::CallbackParam& cb) {
  return cb.return_value != nullptr && cb.return_value->type.is_pointer();
}

// Helper to extract canonical parameter types of a callback.
std::vector<std::string> GetCallbackParamTypes(const ir::CallbackParam& cb) {
  std::vector<std::string> types;
  types.reserve(cb.callback_parameters.size());
  for (const auto& param : cb.callback_parameters) {
    types.push_back(param.type.canonical_name);
  }
  return types;
}

// The function type an invoker's target has, which is the callback typedef's
// own: the invoker's signature with the leading target parameter taken back
// off.
std::string EmitInvokerTargetType(const ir::Function& func) {
  std::vector<std::string> types;
  types.reserve(func.parameters.size() - 1);
  for (size_t i = 1; i < func.parameters.size(); ++i) {
    types.push_back(func.parameters[i].type.canonical_name);
  }
  return absl::Substitute(
      "$0 (*)($1)",
      func.return_value ? func.return_value->type.canonical_name : "void",
      absl::StrJoin(types, ", "));
}

// The entry point that turns a sandboxee function following `typedef_name` into
// a host-callable address. Defined by EmitThunkPool.
std::string BindThunkName(absl::string_view typedef_name) {
  return absl::StrCat("sapi_bind_thunk_", typedef_name);
}

// The entry point that turns a host function following `typedef_name` into a
// sandboxee-callable trampoline address. Defined by EmitThunkPool.
std::string RegisterCallbackName(absl::string_view typedef_name) {
  return absl::StrCat("sapi_register_callback_", typedef_name);
}

// An alias for the function pointer type a callback typedef describes.
//
// A function that returns a function pointer cannot be declared by writing
// the return type in front of the name -- `int (*f(void))(int)` is the only
// spelling, and it is not one that composes with how declarations are built
// here. Going through an alias gives the same type in the ordinary shape.
//
// Keyed on the callback typedef rather than on the returning function, so that
// two functions handing back the same kind of callback share one alias.
// Repeating an identical alias is legal, which is what makes that safe.
std::string CallbackTypedefAliasName(absl::string_view typedef_name) {
  return absl::StrCat("sapi_callback_", typedef_name, "_t");
}

std::string EmitCallbackTypedefAlias(const ir::Parameter& ret,
                                     const ir::SandboxeeCallbackParam& cb) {
  return absl::Substitute("using $0 = $1;\n",
                          CallbackTypedefAliasName(cb.typedef_name),
                          ret.type.canonical_name);
}

// What a value of this type looks like crossing the boundary. A callback the
// sandbox implements travels as the bare address of a sandboxee function;
// everything else travels as itself.
std::string WireTypeName(const ir::Parameter& param) {
  if (param.Is<ir::SandboxeeCallbackParam>()) {
    return "uintptr_t";
  }
  return param.type.canonical_name;
}

// Emits the C++ parameter type declaration for the host wrapper.
std::string EmitHostParamDecl(const ir::Parameter& param) {
  return std::visit(
      absl::Overload{
          [&](const ir::CallbackParam& cb) {
            std::string ret_type = GetCallbackReturnType(cb);
            auto param_types = GetCallbackParamTypes(cb);
            if (cb.functor_template_name.has_value()) {
              return absl::Substitute(
                  "$0<$1($2)> $3", *cb.functor_template_name, ret_type,
                  absl::StrJoin(param_types, ", "), param.name);
            }
            return absl::Substitute("$0 (*$1)($2)", ret_type, param.name,
                                    absl::StrJoin(param_types, ", "));
          },
          [&](const ir::SandboxeeCallbackParam& cb) {
            // Unreachable today: only a return value can be one of these. The
            // alias is still the right spelling, and cheaper than leaving a
            // trap for whoever makes a parameter one.
            return absl::Substitute(
                "$0 $1", CallbackTypedefAliasName(cb.typedef_name), param.name);
          },
          [&](const auto& p) {
            using T = std::decay_t<decltype(p)>;
            static_assert(
                IsOneOf<T, ir::VoidParam, ir::ScalarParam, ir::BufferParam,
                        ir::CppStringParam, ir::OpaquePointerParam,
                        ir::StructSyncParam>,
                "Unhandled parameter payload type in EmitHostParamDecl!");
            return absl::Substitute("$0 $1", param.type.canonical_name,
                                    param.name);
          },
      },
      param.payload);
}

// Emits the C++ parameter type declaration for the sandboxee RPC wrapper.
// For strings and string references, LenValStruct pointers or data/size pairs
// are used.
std::string EmitSandboxeeParamDecl(const ir::Parameter& param) {
  return std::visit(
      absl::Overload{
          [&](const ir::CallbackParam& cb) {
            return absl::Substitute(
                "$0 (*$1)($2)", GetCallbackReturnType(cb), param.name,
                absl::StrJoin(GetCallbackParamTypes(cb), ", "));
          },
          [&](const ir::CppStringParam& str) {
            if (str.form == ir::CppStringParam::Form::kView ||
                str.form == ir::CppStringParam::Form::kValue ||
                (str.form == ir::CppStringParam::Form::kReference &&
                 str.is_const)) {
              return absl::Substitute("const char* $0_data, size_t $0_size",
                                      param.name);
            }
            return absl::Substitute("sapi::LenValStruct* $0", param.name);
          },
          [&](const ir::SandboxeeCallbackParam&) {
            // Unreachable today: only a return value can be one of these,
            // and a return travels through `sapi_ret_arg`.
            return absl::Substitute("uintptr_t $0", param.name);
          },
          [&](const auto& p) {
            using T = std::decay_t<decltype(p)>;
            static_assert(
                IsOneOf<T, ir::VoidParam, ir::ScalarParam, ir::BufferParam,
                        ir::OpaquePointerParam, ir::StructSyncParam>,
                "Unhandled parameter payload type in EmitSandboxeeParamDecl!");
            return absl::Substitute("$0 $1", param.type.canonical_name,
                                    param.name);
          },
      },
      param.payload);
}


// Evaluates to true if T is identical to any of the types in Allowed.
//
// DESIGN NOTE: In visitor patterns over sum types (std::variant), using an
// unconstrained fallback like `[&](const auto&)` can silently swallow new
// variant types introduced in the future, converting what should be a
// compile-time error into a runtime bug.
//
// While C++20 concepts could be defined for fallback whitelists, every
// std::visit in this file partitions parameter types slightly differently
// (e.g., EmitFuncDecl has a different default set than EmitWrapperDecl or
// Sandboxee argument passing), which would lead to an explosion of single-use
// concepts.
//
// Instead, we use `static_assert(IsOneOf<T, ...>, "...")` locally within each
// generic fallback lambda. This guarantees:
// 1. When a new parameter payload is added to ParameterPayload, the build
//    breaks independently at EVERY call site that doesn't explicitly handle it.
// 2. The author is forced to audit each block and make a conscious design
//    decision for that specific code generation phase, flushing out bugs.
// 3. We avoid duplicating boilerplate logic across 6+ variant types.
//
// Example:
//   std::visit(
//       absl::Overload{
//           [&](const ir::CallbackParam& cb) { ... },
//           [&](const auto& p) {
//             using T = std::decay_t<decltype(p)>;
//             static_assert(
//                 IsOneOf<T, ir::VoidParam, ir::ScalarParam, ir::BufferParam,
//                         ir::OpaquePointerParam, ir::StructSyncParam>,
//                 "Unhandled parameter payload type in EmitWrapperDecl!");
//             absl::StrAppend(&out, param.type.canonical_name, " ",
//             param.name);
//           },
//       },
//       param.payload);
template <typename T, typename... Allowed>
inline constexpr bool IsOneOf = (std::is_same_v<T, Allowed> || ...);


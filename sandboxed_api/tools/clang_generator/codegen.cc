absl::StatusOr<std::string> EmitHostSrc(
    const GeneratorOptions& options, const ir::Library& library,
    const absl::flat_hash_set<std::string>& includes) {
  std::string out;
  absl::StrAppendFormat(&out, "#include \"%s\"\n", options.out_file);
  absl::StrAppend(&out,
                  absl::Substitute(kHostHeader, kIncludePrefix, options.name));

  std::vector<const ir::Function*> sorted_funcs = GetSortedFunctions(library);

  if (library.host_code) {
    absl::StrAppend(&out, *library.host_code, "\n\n");
  }

  for (const auto& src : library.host_state_vars) {
    absl::StrAppend(&out, src, "\n");
  }

  for (const auto* func : sorted_funcs) {
    if (func->host_thunk) {
      absl::StrAppend(&out, "// Start of thunk\n");
      // Forward declare the sandboxee thunk, as the host thunk calls into it.
      if (func->sandboxee_thunk) {
        absl::StrAppend(&out, "extern \"C\" ",
                        func->sandboxee_thunk->declaration, ";\n");
      }
      absl::StrAppend(&out, "extern \"C\" ", func->host_thunk->body,
                      "\n// End of thunk\n\n");
      continue;
    }

    EmitFuncDecl(out, *func);
    absl::StrAppend(
        &out, " {\n",
        absl::Substitute("  auto* sandbox = $0SandboxImpl::Instance();\n",
                         options.name),
        absl::Substitute("  $0Api api(sandbox);\n\n", options.name));

    std::string pre_call;
    std::string call_args;
    std::string post_call;

    for (size_t i = 0; i < func->parameters.size(); ++i) {
      if (i > 0) absl::StrAppend(&call_args, ", ");
      EmitHostSrcParam(func->parameters[i], pre_call, call_args, post_call);
    }

    if (func->return_value) {
      if (!func->parameters.empty()) absl::StrAppend(&call_args, ", ");
      if (func->return_value->type.kind == ir::TypeKind::kString) {
        absl::StrAppend(&pre_call,
                        "  sapi::v::LenVal sapi_ret_tmp(nullptr, 0);\n");
        absl::StrAppend(&call_args, "sapi_ret_tmp.PtrAfter()");
      } else {
        absl::StrAppend(
            &pre_call,
            absl::Substitute("  sapi::v::Reg<$0> sapi_ret_arg;\n",
                             func->return_value->type.canonical_name));
        absl::StrAppend(&call_args, "sapi_ret_arg.PtrAfter()");
      }
    }

    for (const auto& param : func->parameters) {
      if (param.should_clear_bindings()) {
        absl::SubstituteAndAppend(
            &post_call,
            "  sapi::lwbox::ContextBindingRegistry::Instance()->"
            "ClearBindings(*sandbox, $0);\n",
            param.name);
      }
    }

    absl::StrAppend(&out, pre_call, "\n");
    absl::StrAppend(&out,
                    absl::Substitute("  sandbox->Check(api.$0$1($2));\n\n",
                                     kWrapperPrefix, func->name, call_args));
    absl::StrAppend(&out, post_call);

    // Context bound post-call data binding
    for (const auto& bind : func->context_bound.bind_data) {
      std::string ctx_name = ResolveContextName(bind.context);
      absl::StrAppend(
          &out,
          absl::Substitute(
              "  if ($0 != nullptr) {\n"
              "    sapi::lwbox::ContextBindingRegistry::Instance()->BindSize(\n"
              "        $0, \"$2\", $1);\n"
              "  }\n",
              ctx_name, bind.host_computable_expr, bind.binding_name));
    }

    if (func->return_value) {
      std::visit(
          absl::Overload{
              [&](const ir::CppStringParam&) {
                absl::StrAppend(
                    &out,
                    "  return "
                    "std::string(reinterpret_cast<char*>("
                    "sapi_ret_tmp.GetData()), sapi_ret_tmp.GetDataSize());\n");
              },
              [&](const ir::BufferParam& ret_buf) {
                if (const auto* alias = std::get_if<ir::lifetime::AliasHostPtr>(
                        &ret_buf.lifetime)) {
                  absl::StrAppend(
                      &out,
                      absl::Substitute(
                          "  return sapi_ret_arg.GetValue() ? $0 : nullptr;\n",
                          alias->host_param_name));
                } else if (const auto* alias_cb =
                               std::get_if<ir::lifetime::AliasCallbackReturn>(
                                   &ret_buf.lifetime)) {
                  absl::SubstituteAndAppend(
                      &out,
                      "  return sapi_ret_arg.GetValue()\n"
                      "             ? static_cast<$0>(\n"
                      "                   "
                      "sapi_alias_cb_return_map_$1[reinterpret_cast<uintptr_"
                      "t>(\n"
                      "                       sapi_ret_arg.GetValue())])\n"
                      "             : nullptr;\n",
                      func->return_value->type.canonical_name,
                      alias_cb->callback_param_name);
                } else if (ret_buf.context_bound.copy_from_and_bind
                               .has_value()) {
                  absl::StrAppend(&out,
                                  EmitCopyFromAndBindOutPtrCode(
                                      *ret_buf.context_bound.copy_from_and_bind,
                                      "sapi_ret_arg",
                                      func->return_value->type.canonical_name,
                                      ret_buf.bounds));
                  absl::StrAppend(&out, "  return sapi_ret_arg.GetValue();\n");
                } else if (std::holds_alternative<ir::lifetime::SandboxGlobal>(
                               ret_buf.lifetime)) {
                  absl::SubstituteAndAppend(
                      &out,
                      "  return sapi::lwbox::GlobalStringRegistry::Instance()"
                      "->GetOrFetch(*sandbox, sapi_ret_arg.GetValue());\n");
                } else {
                  absl::StrAppend(&out, "  return sapi_ret_arg.GetValue();\n");
                }
              },
              [&](const auto& p) {
                using T = std::decay_t<decltype(p)>;
                static_assert(
                    IsOneOf<T, ir::VoidParam, ir::ScalarParam,
                            ir::OpaquePointerParam, ir::StructSyncParam,
                            ir::CallbackParam>,
                    "Unhandled return value payload type in HostSrc!");
                absl::StrAppend(&out, "  return sapi_ret_arg.GetValue();\n");
              },
          },
          func->return_value->payload);
    }
    absl::StrAppend(&out, "}\n\n");
  }

  absl::flat_hash_set<std::string> host_includes =
      GatherHostIncludes(library, sorted_funcs, includes);
  return FinalizeCode(out, /*is_header=*/false, /*add_includes=*/true,
                      host_includes);
}


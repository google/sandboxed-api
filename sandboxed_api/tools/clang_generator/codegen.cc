// Returns sorted function pointers from the IR library by function name.
std::vector<const ir::Function*> GetSortedFunctions(
    const ir::Library& library) {
  std::vector<const ir::Function*> sorted;
  sorted.reserve(library.functions.size());
  for (const auto& func : library.functions) {
    sorted.push_back(&func);
  }
  std::sort(sorted.begin(), sorted.end(),
            [](const ir::Function* a, const ir::Function* b) {
              return a->name < b->name;
            });
  return sorted;
}

// Emits `#include` directives for headers specified in GeneratorOptions.
void EmitLibraryHeaders(const GeneratorOptions& options, std::string& out) {
  std::vector<std::string> sorted_headers(options.library_headers.begin(),
                                          options.library_headers.end());
  std::sort(sorted_headers.begin(), sorted_headers.end());
  for (const auto& header : sorted_headers) {
    absl::StrAppendFormat(&out, "#include \"%s\"\n", header);
  }
}

// Consumes a leading C identifier from `s`, modifying `s` in place. Returns
// true if an identifier was consumed.
bool ConsumeIdentifier(absl::string_view& s) {
  size_t len = 0;
  while (len < s.size() && ((len == 0 ? absl::ascii_isalpha(s[len])
                                      : absl::ascii_isalnum(s[len])) ||
                            s[len] == '_')) {
    ++len;
  }
  s.remove_prefix(len);
  return len > 0;
}

// Compiles a context binding expression (e.g. "$name" or "$name * 2") into
// a runtime lookup against sapi::lwbox::ContextBindingRegistry.
std::string CompileBindingExpr(absl::string_view context_var,
                               absl::string_view expr) {
  if (!absl::StrContains(expr, '$')) {
    absl::string_view rest = expr;
    if (ConsumeIdentifier(rest) && rest.empty()) {
      return absl::Substitute(
          "sapi::lwbox::ContextBindingRegistry::Instance()->GetSize($0, "
          "\"$1\")",
          context_var, expr);
    }
    return std::string(expr);
  }

  // Scan for `$name` references. Anything else, including a `$` that is not
  // followed by an identifier, is passed through unchanged.
  std::string result;
  size_t pos = 0;
  while (pos < expr.size()) {
    if (expr[pos] != '$') {
      result.push_back(expr[pos]);
      ++pos;
      continue;
    }
    size_t id_begin = pos + 1;
    absl::string_view rest = expr.substr(id_begin);
    if (!ConsumeIdentifier(rest)) {
      result.push_back(expr[pos]);
      ++pos;
      continue;
    }
    size_t id_end = expr.size() - rest.size();
    absl::SubstituteAndAppend(
        &result,
        "sapi::lwbox::ContextBindingRegistry::Instance()->GetSize($0, \"$1\")",
        context_var, expr.substr(id_begin, id_end - id_begin));
    pos = id_end;
  }
  return result;
}

// Returns true if `type` is a pointer to `const char` (or a pointer to
// `const char*` for global string output parameters).
bool IsConstCharPointee(const ir::TypeInfo& type) {
  if (!type.is_pointer() || type.pointee == nullptr) {
    return false;
  }
  if (type.pointee->canonical_name == "const char") {
    return true;
  }
  return type.pointee->is_pointer() && type.pointee->pointee != nullptr &&
         type.pointee->pointee->canonical_name == "const char";
}

// Returns true if a buffer is emitted through the dedicated null-terminated
// C-string path (`sapi::v::ConstCStr` / `sapi::v::Reg<const char*>`) rather
// than the generic buffer machinery.
//
// The IR represents every null-terminated pointer as a `BufferParam` with
// `kNullTerminated` bounds; picking an emission strategy for it is an emitter
// concern. Non-`char` null-terminated arrays (e.g. `const unsigned char*`,
// `const char16_t*`, `const int*`) and strings that additionally carry a retain
// or copy-from-and-bind annotation stay on the generic buffer path.
bool UsesCStringEmission(const ir::Parameter& param,
                         const ir::BufferParam& buf) {
  return IsConstCharPointee(param.type) && buf.pointee == nullptr &&
         std::holds_alternative<ir::bounds::NullTerminated>(buf.bounds) &&
         !buf.context_bound.copy_from_and_bind.has_value() &&
         !buf.context_bound.retain_and_bind.has_value();
}

// Computes the maximum allocation capacity in bytes for a buffer parameter.
// Capacity is always in bytes.
std::string GetParamCapacityAsBytesExpr(const ir::Parameter& param,
                                        const ir::BufferParam& buf) {
  return std::visit(
      absl::Overload{
          [&](const ir::bounds::Singleton&) {
            DCHECK(!param.type.is_pointee_void())
                << "void* buffer parameter must have byte-based bounds";
            return absl::Substitute("sizeof(*$0)", param.name);
          },
          [&](const ir::bounds::ElemCount& elem) {
            DCHECK(!param.type.is_pointee_void())
                << "void* buffer parameter cannot use element-count bounds";
            return absl::Substitute(
                "sandbox->CheckedMultiply(sizeof(*$0), ($1))", param.name,
                elem.size_expr);
          },
          [](const ir::bounds::ByteCount& byte) { return byte.size_expr; },
          [&](const ir::bounds::ElemSizedByOutparam& elem) {
            DCHECK(!elem.capacity_expr.empty());
            return elem.capacity_expr;
          },
          [&](const ir::bounds::ByteSizedByOutparam& byte) {
            DCHECK(!byte.capacity_expr.empty());
            return byte.capacity_expr;
          },
          [](const ir::bounds::SizedByBinding& binding) {
            std::string context_var = ResolveContextName(binding.context_expr);
            return CompileBindingExpr(context_var, binding.binding_name);
          },
          [&](const ir::bounds::NullTerminated&) {
            if (IsConstCharPointee(param.type)) {
              return absl::Substitute(
                  "strlen(reinterpret_cast<const char*>($0)) + 1", param.name);
            }
            return absl::Substitute("sapi::lwbox::NullTerminatedByteSize($0)",
                                    param.name);
          },
      },
      buf.bounds);
}

// Computes the active data size in bytes for a buffer parameter.
std::string GetParamSizeAsBytesExpr(const ir::Parameter& param,
                                    const ir::BufferParam& buf) {
  return std::visit(
      absl::Overload{
          [&](const ir::bounds::Singleton&) {
            DCHECK(!param.type.is_pointee_void())
                << "void* buffer parameter must have byte-based bounds";
            return absl::Substitute("sizeof(*$0)", param.name);
          },
          [&](const ir::bounds::ElemCount& elem) {
            DCHECK(!param.type.is_pointee_void())
                << "void* buffer parameter cannot use element-count bounds";
            return absl::Substitute(
                "sandbox->CheckedMultiply(sizeof(*$0), ($1))", param.name,
                elem.size_expr);
          },
          [&](const ir::bounds::ElemSizedByOutparam& elem) {
            DCHECK(!param.type.is_pointee_void())
                << "void* buffer parameter cannot use element-count bounds";
            return absl::Substitute(
                "sandbox->CheckedMultiply(sizeof(*$0), (*$1))", param.name,
                elem.outparam_name);
          },
          [](const ir::bounds::ByteCount& byte) { return byte.size_expr; },
          [](const ir::bounds::ByteSizedByOutparam& byte) {
            return absl::StrCat("*", byte.outparam_name);
          },
          [](const ir::bounds::SizedByBinding& binding) {
            std::string context_var = ResolveContextName(binding.context_expr);
            return CompileBindingExpr(context_var, binding.binding_name);
          },
          [&](const ir::bounds::NullTerminated&) {
            if (IsConstCharPointee(param.type)) {
              return absl::Substitute(
                  "strlen(reinterpret_cast<const char*>($0)) + 1", param.name);
            }
            return absl::Substitute("sapi::lwbox::NullTerminatedByteSize($0)",
                                    param.name);
          },
      },
      buf.bounds);
}

// Returns true if buffer sizing depends on an output parameter (e.g. *out_len).
bool IsSizeBasedOnDerefOutParam(const ir::BufferParam& buf) {
  return std::holds_alternative<ir::bounds::ElemSizedByOutparam>(buf.bounds) ||
         std::holds_alternative<ir::bounds::ByteSizedByOutparam>(buf.bounds);
}


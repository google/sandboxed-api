void EmitFuncDecl(std::string& out, const ir::Function& func) {
  std::string ret = "void";
  if (func.return_value) {
    ret = func.return_value->type.canonical_name;
  }
  absl::StrAppend(&out,
                  absl::Substitute("extern \"C\" $0 $1(", ret, func.name));
  for (size_t i = 0; i < func.parameters.size(); ++i) {
    if (i > 0) {
      absl::StrAppend(&out, ", ");
    }
    absl::StrAppend(&out, EmitHostParamDecl(func.parameters[i]));
  }
  absl::StrAppend(&out, ")");
}

void EmitWrapperDecl(std::string& out, const ir::Function& func) {
  std::string ret = "void";
  absl::StrAppend(
      &out,
      absl::Substitute("extern \"C\" __attribute__((used, retain)) $0 $1$2(",
                       ret, kWrapperPrefix, func.name));
  bool first = true;
  for (const auto& param : func.parameters) {
    if (!first) {
      absl::StrAppend(&out, ", ");
    }
    first = false;
    absl::StrAppend(&out, EmitSandboxeeParamDecl(param));
  }

  if (func.return_value) {
    if (!first) {
      absl::StrAppend(&out, ", ");
    }
    if (func.return_value->type.kind == ir::TypeKind::kString) {
      absl::StrAppend(&out, "sapi::LenValStruct* sapi_ret_arg");
    } else {
      absl::StrAppend(&out, func.return_value->type.canonical_name,
                      "* sapi_ret_arg");
    }
  }

  absl::StrAppend(&out, ")");
}


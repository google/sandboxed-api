namespace {

// Returns true if the pointer value described by `pointee_param` is written or
// returned directly by the sandboxee as a remote pointer/handle (which must be
// transferred out of the pointer cell and translated on the host), as opposed
// to a host-allocated shadow buffer whose remote address is placed into the
// pointer cell before the call.
bool IsCalleeWrittenPointerValue(const ir::Parameter& pointee_param) {
  if (pointee_param.Is<ir::OpaquePointerParam>()) {
    return true;
  }
  if (const auto* buf = pointee_param.As<ir::BufferParam>()) {
    if (buf->pointee != nullptr) {
      return false;
    }
    if (buf->context_bound.copy_from_and_bind.has_value()) {
      return true;
    }
    if (UsesCStringEmission(pointee_param, *buf) &&
        std::holds_alternative<ir::lifetime::SandboxGlobal>(buf->lifetime)) {
      return pointee_param.IsOutput();
    }
  }
  return false;
}

// Returns true if the leaf buffer at the bottom of a multi-level pointer chain
// transfers output data back to the host via `sapi_sync_out_<param>`.
bool HasShadowLeafOutputBuffer(const ir::Parameter& pointee_param) {
  const ir::Parameter* cur = &pointee_param;
  while (const auto* buf = cur->As<ir::BufferParam>()) {
    if (buf->pointee == nullptr) {
      return !IsCalleeWrittenPointerValue(*cur) && cur->IsOutput();
    }
    cur = buf->pointee.get();
  }
  return false;
}

// Emits pre-call conversion of a single host pointer expression `host_expr`
// (described by `inner_param` when `IsCalleeWrittenPointerValue(inner_param)`
// is true) into a remote pointer value stored in `remote_lhs`.
void EmitCalleeWrittenPointerPreCall(
    const ir::Parameter& inner_param, absl::string_view top_param_name,
    absl::string_view host_expr, absl::string_view remote_lhs,
    absl::string_view indent, bool uses_owned_vars, std::string& pre_call) {
  if (inner_param.Is<ir::OpaquePointerParam>()) {
    absl::SubstituteAndAppend(&pre_call, "$0$1 = $2;\n", indent, remote_lhs,
                              host_expr);
    return;
  }
  if (const auto* buf = inner_param.As<ir::BufferParam>()) {
    if (UsesCStringEmission(inner_param, *buf)) {
      if (uses_owned_vars && inner_param.IsInput()) {
        absl::SubstituteAndAppend(
            &pre_call,
            "$0if (($1) != nullptr) {\n"
            "$0  auto sapi_cstr = std::make_unique<sapi::v::ConstCStr>($1);\n"
            "$0  sandbox->Check(sandbox->Allocate(sapi_cstr.get(), "
            "/*automatic_free=*/true));\n"
            "$0  "
            "sandbox->Check(sandbox->TransferToSandboxee(sapi_cstr.get()));\n"
            "$0  $2 = reinterpret_cast<const char*>(sapi_cstr->GetRemote());\n"
            "$0  sapi_owned_$3.push_back(std::move(sapi_cstr));\n"
            "$0}\n",
            indent, host_expr, remote_lhs, top_param_name);
      }
    }
  }
}

// Emits post-call translation of a remote pointer expression `remote_expr`
// back into the host lvalue `host_lhs` (when
// `IsCalleeWrittenPointerValue(inner_param)` is true).
void EmitCalleeWrittenPointerPostCall(const ir::Parameter& inner_param,
                                      absl::string_view host_lhs,
                                      absl::string_view remote_expr,
                                      absl::string_view indent,
                                      std::string& post_call) {
  if (inner_param.Is<ir::OpaquePointerParam>()) {
    absl::SubstituteAndAppend(&post_call, "$0$1 = $2;\n", indent, host_lhs,
                              remote_expr);
    return;
  }
  if (const auto* buf = inner_param.As<ir::BufferParam>()) {
    if (UsesCStringEmission(inner_param, *buf) &&
        std::holds_alternative<ir::lifetime::SandboxGlobal>(buf->lifetime)) {
      absl::SubstituteAndAppend(
          &post_call,
          "$0$1 = sapi::lwbox::GlobalStringRegistry::Instance()->GetOrFetch(\n"
          "$0    *sandbox, $2);\n",
          indent, host_lhs, remote_expr);
    }
  }
}

// Recursively emits pre-call allocation and transfer for a shadow pointer
// element `host_expr` at depth >= 1, storing its sandboxee remote address in
// `remote_lhs`.
void EmitShadowPointerElement(const ir::Parameter& inner_param,
                              absl::string_view top_param_name,
                              absl::string_view host_expr,
                              absl::string_view remote_lhs, int depth,
                              absl::string_view indent, std::string& pre_call,
                              std::string& post_call) {
  if (IsCalleeWrittenPointerValue(inner_param)) {
    EmitCalleeWrittenPointerPreCall(inner_param, top_param_name, host_expr,
                                    remote_lhs, indent,
                                    /*uses_owned_vars=*/true, pre_call);
    return;
  }

  const auto* inner_buf = inner_param.As<ir::BufferParam>();
  if (inner_buf == nullptr) {
    return;
  }

  std::string inner_type = inner_param.type.canonical_name;
  if (inner_param.type.is_const && absl::EndsWith(inner_type, "const")) {
    inner_type = std::string(absl::StripAsciiWhitespace(
        absl::string_view(inner_type).substr(0, inner_type.size() - 5)));
  }

  if (UsesCStringEmission(inner_param, *inner_buf)) {
    absl::SubstituteAndAppend(
        &pre_call,
        "$0if (($1) != nullptr) {\n"
        "$0  auto sapi_cstr = std::make_unique<sapi::v::ConstCStr>($1);\n"
        "$0  sandbox->Check(sandbox->Allocate(sapi_cstr.get(), "
        "/*automatic_free=*/true));\n"
        "$0  sandbox->Check(sandbox->TransferToSandboxee(sapi_cstr.get()));\n"
        "$0  $2 = reinterpret_cast<const char*>(sapi_cstr->GetRemote());\n"
        "$0  sapi_owned_$3.push_back(std::move(sapi_cstr));\n"
        "$0}\n",
        indent, host_expr, remote_lhs, top_param_name);
    return;
  }

  if (inner_buf->pointee == nullptr) {
    ir::Parameter synthetic_param{
        .name = absl::StrCat("(", host_expr, ")"),
        .type = inner_param.type,
    };
    std::string cap_expr =
        GetParamCapacityAsBytesExpr(synthetic_param, *inner_buf);
    std::string transfer_in;
    if (inner_param.IsInput()) {
      transfer_in = absl::Substitute(
          "$0  sandbox->Check(sandbox->TransferToSandboxee(sapi_arr.get()));\n",
          indent);
    }
    std::string record_out;
    if (inner_param.IsOutput()) {
      record_out =
          absl::Substitute("$0  sapi_sync_out_$1.push_back(sapi_arr.get());\n",
                           indent, top_param_name);
    }
    absl::SubstituteAndAppend(
        &pre_call,
        "$0if (($1) != nullptr) {\n"
        "$0  auto sapi_arr = std::make_unique<sapi::v::Array<char>>(\n"
        "$0      const_cast<char*>(reinterpret_cast<const char*>($1)),\n"
        "$0      $2);\n"
        "$0  sandbox->Check(sandbox->Allocate(sapi_arr.get(), "
        "/*automatic_free=*/true));\n"
        "$3"
        "$0  $4 = reinterpret_cast<$5>(sapi_arr->GetRemote());\n"
        "$6"
        "$0  sapi_owned_$7.push_back(std::move(sapi_arr));\n"
        "$0}\n",
        indent, host_expr, cap_expr, transfer_in, remote_lhs, inner_type,
        record_out, top_param_name);
    return;
  }

  // Nested multi-level pointer (`inner_buf->pointee != nullptr`, e.g., T***).
  std::string child_ptr_type = inner_param.type.pointee_value_type_name();
  bool is_null_terminated =
      std::holds_alternative<ir::bounds::NullTerminated>(inner_buf->bounds);
  std::string count_expr = std::visit(
      absl::Overload{
          [](const ir::bounds::Singleton&) -> std::string { return "1"; },
          [](const ir::bounds::ElemCount& e) -> std::string {
            return e.size_expr;
          },
          [&](const ir::bounds::ByteCount& b) -> std::string {
            return absl::Substitute("(($0) / sizeof($1))", b.size_expr,
                                    child_ptr_type);
          },
          [&](const ir::bounds::NullTerminated&) -> std::string {
            return absl::Substitute("sapi::lwbox::NullTerminatedCount($0)",
                                    host_expr);
          },
          [](const auto&) -> std::string { return "1"; },
      },
      inner_buf->bounds);
  bool is_singleton =
      std::holds_alternative<ir::bounds::Singleton>(inner_buf->bounds);
  bool child_is_callee_written =
      IsCalleeWrittenPointerValue(*inner_buf->pointee);

  std::string idx_var = absl::StrCat("sapi_idx_d", depth);
  std::string cnt_var = absl::StrCat("sapi_cnt_d", depth);
  std::string child_indent = absl::StrCat(indent, "  ");
  std::string tbl_slots_expr =
      is_null_terminated ? absl::Substitute("($0 + 1)", cnt_var)
                         : absl::Substitute("std::max<size_t>($0, 1)", cnt_var);
  std::string tbl_xfer_count_expr =
      is_null_terminated ? absl::Substitute("$0 + 1", cnt_var) : cnt_var;

  absl::SubstituteAndAppend(
      &pre_call,
      "$0if (($1) != nullptr) {\n"
      "$0  size_t $2 = static_cast<size_t>($3);\n"
      "$0  auto sapi_tbl = std::make_unique<std::vector<char>>(\n"
      "$0      sandbox->CheckedMultiply(sizeof($4), $5), 0);\n",
      indent, host_expr, cnt_var, count_expr, child_ptr_type, tbl_slots_expr);

  if (!child_is_callee_written || inner_param.IsInput()) {
    absl::SubstituteAndAppend(&pre_call,
                              "$0  auto* sapi_child_ptrs = "
                              "reinterpret_cast<$1*>(sapi_tbl->data());\n",
                              indent, child_ptr_type);
    if (is_singleton) {
      std::string child_host = absl::Substitute("*($0)", host_expr);
      EmitShadowPointerElement(*inner_buf->pointee, top_param_name, child_host,
                               "sapi_child_ptrs[0]", depth + 1, child_indent,
                               pre_call, post_call);
    } else {
      std::string loop_indent = absl::StrCat(child_indent, "  ");
      absl::SubstituteAndAppend(&pre_call,
                                "$0for (size_t $1 = 0; $1 < $2; ++$1) {\n",
                                child_indent, idx_var, cnt_var);
      std::string child_host = absl::Substitute("($0)[$1]", host_expr, idx_var);
      std::string child_lhs = absl::Substitute("sapi_child_ptrs[$0]", idx_var);
      EmitShadowPointerElement(*inner_buf->pointee, top_param_name, child_host,
                               child_lhs, depth + 1, loop_indent, pre_call,
                               post_call);
      absl::SubstituteAndAppend(&pre_call, "$0}\n", child_indent);
    }
  }

  absl::SubstituteAndAppend(
      &pre_call,
      "$0  auto sapi_tbl_arr = std::make_unique<sapi::v::Array<char>>(\n"
      "$0      sapi_tbl->data(),\n"
      "$0      sandbox->CheckedMultiply(sizeof($1), $2));\n"
      "$0  sandbox->Check(sandbox->Allocate(sapi_tbl_arr.get(), "
      "/*automatic_free=*/true));\n"
      "$0  sandbox->Check(sandbox->TransferToSandboxee(sapi_tbl_arr.get()));\n"
      "$0  $3 = reinterpret_cast<$4>(sapi_tbl_arr->GetRemote());\n",
      indent, child_ptr_type, tbl_xfer_count_expr, remote_lhs, inner_type);

  if (child_is_callee_written && inner_param.IsOutput() && depth == 1) {
    absl::SubstituteAndAppend(&pre_call,
                              "$0  sapi_callee_tbl_$1 = sapi_tbl_arr.get();\n"
                              "$0  sapi_callee_cnt_$1 = $2;\n",
                              indent, top_param_name, cnt_var);
    if (is_singleton) {
      std::string child_host = absl::Substitute("*($0)", host_expr);
      std::string remote_val = absl::Substitute(
          "reinterpret_cast<$0*>(sapi_callee_tbl_$1->GetLocal())[0]",
          child_ptr_type, top_param_name);
      std::string sync_stmt;
      EmitCalleeWrittenPointerPostCall(*inner_buf->pointee, child_host,
                                       remote_val, "    ", sync_stmt);
      absl::SubstituteAndAppend(
          &post_call,
          "  if (sapi_callee_tbl_$0 != nullptr) {\n"
          "    sandbox->Check(\n"
          "        sandbox->TransferFromSandboxee(sapi_callee_tbl_$0));\n"
          "$1"
          "  }\n",
          top_param_name, sync_stmt);
    } else {
      std::string child_host = absl::Substitute("($0)[sapi_i]", host_expr);
      std::string remote_val = absl::Substitute(
          "reinterpret_cast<$0*>(sapi_callee_tbl_$1->GetLocal())[sapi_i]",
          child_ptr_type, top_param_name);
      std::string sync_stmt;
      EmitCalleeWrittenPointerPostCall(*inner_buf->pointee, child_host,
                                       remote_val, "      ", sync_stmt);
      absl::SubstituteAndAppend(
          &post_call,
          "  if (sapi_callee_tbl_$0 != nullptr) {\n"
          "    sandbox->Check(\n"
          "        sandbox->TransferFromSandboxee(sapi_callee_tbl_$0));\n"
          "    for (size_t sapi_i = 0; sapi_i < sapi_callee_cnt_$0; ++sapi_i) "
          "{\n"
          "$1"
          "    }\n"
          "  }\n",
          top_param_name, sync_stmt);
    }
  }

  absl::SubstituteAndAppend(
      &pre_call,
      "$0  sapi_tables_$1.push_back(std::move(sapi_tbl));\n"
      "$0  sapi_owned_$1.push_back(std::move(sapi_tbl_arr));\n"
      "$0}\n",
      indent, top_param_name);
}

// Emits host-side pre-call, call argument, and post-call marshaling for a
// multi-level pointer parameter (`buf.pointee != nullptr`).
//
// Security invariant (pointer-table integrity & double-fetch prevention):
// When `!child_is_callee_written` (e.g., `int** grid` or `int*** tensor` where
// the leaf pointees are caller-owned buffers), the pointer tables (`sapi_ptrs_`
// and `sapi_tbl`) are transferred one-way into the sandboxee (`PtrBefore()`)
// and all leaf output buffers are recorded on the host in `sapi_sync_out_`
// before the call. Post-call synchronization iterates over `sapi_sync_out_`
// directly rather than re-reading the pointer table from sandboxee memory, so a
// compromised sandboxee that overwrites `grid[r]` in its own address space
// cannot redirect host writebacks or corrupt the caller's host pointers.
// When `child_is_callee_written` is true (`SANDBOX_OPAQUE_PTR` or
// `SANDBOX_LIFETIME_GLOBAL` C-strings), the pointer table is copied into a
// host staging buffer once after the call and translated from that host copy
// (`GlobalStringRegistry::GetOrFetch`).
void EmitMultiLevelPointerParam(const ir::Parameter& param,
                                const ir::BufferParam& buf,
                                std::string& pre_call, std::string& call_args,
                                std::string& post_call) {
  const ir::Parameter& inner_param = *buf.pointee;
  std::string inner_ptr_type = param.type.pointee_value_type_name();
  bool is_singleton = std::holds_alternative<ir::bounds::Singleton>(buf.bounds);
  bool child_is_callee_written = IsCalleeWrittenPointerValue(inner_param);
  bool has_leaf_out = HasShadowLeafOutputBuffer(inner_param);

  // Check if any inner level is itself a multi-level pointer (depth >= 3) or
  // allocates shadow `sapi::v::Var` instances.
  const auto* inner_buf = inner_param.As<ir::BufferParam>();
  bool is_depth_3_or_more =
      inner_buf != nullptr && inner_buf->pointee != nullptr;
  bool needs_owned_vars =
      !child_is_callee_written ||
      (inner_buf != nullptr && UsesCStringEmission(inner_param, *inner_buf) &&
       (buf.direction == PointerDir::kIn ||
        buf.direction == PointerDir::kInOut) &&
       inner_param.IsInput());

  if (needs_owned_vars) {
    absl::SubstituteAndAppend(
        &pre_call,
        "  std::vector<std::unique_ptr<sapi::v::Var>> sapi_owned_$0;\n",
        param.name);
  }
  if (is_depth_3_or_more) {
    absl::SubstituteAndAppend(
        &pre_call,
        "  std::vector<std::unique_ptr<std::vector<char>>> sapi_tables_$0;\n",
        param.name);
    if (IsCalleeWrittenPointerValue(*inner_buf->pointee) &&
        inner_param.IsOutput()) {
      absl::SubstituteAndAppend(
          &pre_call,
          "  sapi::v::Array<char>* sapi_callee_tbl_$0 = nullptr;\n"
          "  size_t sapi_callee_cnt_$0 = 0;\n",
          param.name);
    }
  }
  if (has_leaf_out) {
    absl::SubstituteAndAppend(
        &pre_call, "  std::vector<sapi::v::Var*> sapi_sync_out_$0;\n",
        param.name);
  }

  if (is_singleton) {
    if (child_is_callee_written) {
      if (inner_buf != nullptr &&
          inner_buf->context_bound.copy_from_and_bind.has_value()) {
        DCHECK_EQ(buf.direction, PointerDir::kOut);
        absl::SubstituteAndAppend(&pre_call,
                                  "  sapi::v::Reg<$0> sapi_tmp_$1(nullptr);\n",
                                  inner_ptr_type, param.name);
        absl::SubstituteAndAppend(
            &call_args, "$0 == nullptr ? nullptr : sapi_tmp_$0.PtrAfter()",
            param.name);
        absl::StrAppend(&post_call,
                        EmitCopyFromAndBindOutPtrCode(
                            *inner_buf->context_bound.copy_from_and_bind,
                            absl::StrCat("sapi_tmp_", param.name),
                            inner_ptr_type, inner_buf->bounds));
        absl::SubstituteAndAppend(&post_call,
                                  "  if ($0 != nullptr) {\n"
                                  "    *$0 = sapi_tmp_$0.GetValue();\n"
                                  "  }\n",
                                  param.name);
        return;
      }

      absl::SubstituteAndAppend(&pre_call, "  $0 sapi_remote_$1 = nullptr;\n",
                                inner_ptr_type, param.name);
      if (buf.direction == PointerDir::kIn ||
          buf.direction == PointerDir::kInOut) {
        absl::SubstituteAndAppend(&pre_call, "  if ($0 != nullptr) {\n",
                                  param.name);
        EmitCalleeWrittenPointerPreCall(
            inner_param, param.name, absl::StrCat("*", param.name),
            absl::StrCat("sapi_remote_", param.name), "    ", needs_owned_vars,
            pre_call);
        absl::StrAppend(&pre_call, "  }\n");
      }
      absl::SubstituteAndAppend(
          &pre_call, "  sapi::v::Reg<$0> sapi_tmp_$1(sapi_remote_$1);\n",
          inner_ptr_type, param.name);
      std::string ptr_access =
          (buf.direction == PointerDir::kIn)
              ? "PtrBefore()"
              : ((buf.direction == PointerDir::kOut) ? "PtrAfter()"
                                                     : "PtrBoth()");
      absl::SubstituteAndAppend(&call_args,
                                "$0 == nullptr ? nullptr : sapi_tmp_$0.$1",
                                param.name, ptr_access);
      if (buf.direction == PointerDir::kOut ||
          buf.direction == PointerDir::kInOut) {
        absl::SubstituteAndAppend(&post_call, "  if ($0 != nullptr) {\n",
                                  param.name);
        EmitCalleeWrittenPointerPostCall(
            inner_param, absl::StrCat("*", param.name),
            absl::Substitute("sapi_tmp_$0.GetValue()", param.name), "    ",
            post_call);
        absl::StrAppend(&post_call, "  }\n");
      }
      return;
    }

    // Singleton outer pointer to a shadow buffer or nested multi-level pointer.
    absl::SubstituteAndAppend(&pre_call,
                              "  $0 sapi_remote_$1 = nullptr;\n"
                              "  if ($1 != nullptr) {\n",
                              inner_ptr_type, param.name);
    EmitShadowPointerElement(inner_param, param.name,
                             absl::StrCat("*", param.name),
                             absl::StrCat("sapi_remote_", param.name),
                             /*depth=*/1, "    ", pre_call, post_call);
    absl::SubstituteAndAppend(
        &pre_call,
        "  }\n"
        "  sapi::v::Reg<$0> sapi_tmp_$1(sapi_remote_$1);\n",
        inner_ptr_type, param.name);
    absl::SubstituteAndAppend(
        &call_args, "$0 == nullptr ? nullptr : sapi_tmp_$0.PtrBefore()",
        param.name);
  } else if (std::holds_alternative<ir::bounds::NullTerminated>(buf.bounds)) {
    absl::SubstituteAndAppend(
        &pre_call,
        "  size_t sapi_count_$0 = sapi::lwbox::NullTerminatedCount($0);\n"
        "  std::vector<$1> sapi_ptrs_$0(sapi_count_$0 + 1, nullptr);\n"
        "  for (size_t sapi_i = 0; sapi_i < sapi_count_$0; ++sapi_i) {\n",
        param.name, inner_ptr_type);
    EmitShadowPointerElement(
        inner_param, param.name, absl::Substitute("$0[sapi_i]", param.name),
        absl::Substitute("sapi_ptrs_$0[sapi_i]", param.name),
        /*depth=*/1, "    ", pre_call, post_call);
    absl::SubstituteAndAppend(
        &pre_call,
        "  }\n"
        "  sapi::v::Array<char> sapi_tmp_$0(\n"
        "      reinterpret_cast<char*>(sapi_ptrs_$0.data()),\n"
        "      sandbox->CheckedMultiply(sizeof($1), sapi_count_$0 + 1));\n",
        param.name, inner_ptr_type);
    absl::SubstituteAndAppend(
        &call_args, "$0 == nullptr ? nullptr : sapi_tmp_$0.PtrBefore()",
        param.name);
  } else {
    // Array outer pointer (`ElemCount` or `ByteCount`).
    std::string count_expr =
        std::visit(absl::Overload{
                       [](const ir::bounds::ElemCount& e) -> std::string {
                         return e.size_expr;
                       },
                       [&](const ir::bounds::ByteCount& b) -> std::string {
                         return absl::Substitute("(($0) / sizeof($1))",
                                                 b.size_expr, inner_ptr_type);
                       },
                       [](const auto&) -> std::string { return "1"; },
                   },
                   buf.bounds);
    absl::SubstituteAndAppend(
        &pre_call,
        "  size_t sapi_count_$0 = ($0 != nullptr) ? static_cast<size_t>($1) : "
        "0;\n"
        "  std::vector<$2> sapi_ptrs_$0(std::max<size_t>(sapi_count_$0, 1), "
        "nullptr);\n",
        param.name, count_expr, inner_ptr_type);

    if (!child_is_callee_written || buf.direction == PointerDir::kIn ||
        buf.direction == PointerDir::kInOut) {
      absl::SubstituteAndAppend(
          &pre_call,
          "  for (size_t sapi_i = 0; sapi_i < sapi_count_$0; ++sapi_i) {\n",
          param.name);
      EmitShadowPointerElement(
          inner_param, param.name, absl::Substitute("$0[sapi_i]", param.name),
          absl::Substitute("sapi_ptrs_$0[sapi_i]", param.name),
          /*depth=*/1, "    ", pre_call, post_call);
      absl::StrAppend(&pre_call, "  }\n");
    }

    absl::SubstituteAndAppend(
        &pre_call,
        "  sapi::v::Array<char> sapi_tmp_$0(\n"
        "      reinterpret_cast<char*>(sapi_ptrs_$0.data()),\n"
        "      sandbox->CheckedMultiply(sizeof($1), sapi_count_$0));\n",
        param.name, inner_ptr_type);

    std::string ptr_access = "PtrBefore()";
    if (child_is_callee_written) {
      ptr_access = (buf.direction == PointerDir::kIn)
                       ? "PtrBefore()"
                       : ((buf.direction == PointerDir::kOut) ? "PtrAfter()"
                                                              : "PtrBoth()");
    }
    absl::SubstituteAndAppend(&call_args,
                              "$0 == nullptr ? nullptr : sapi_tmp_$0.$1",
                              param.name, ptr_access);

    if (child_is_callee_written && (buf.direction == PointerDir::kOut ||
                                    buf.direction == PointerDir::kInOut)) {
      absl::SubstituteAndAppend(
          &post_call,
          "  for (size_t sapi_i = 0; sapi_i < sapi_count_$0; ++sapi_i) {\n",
          param.name);
      EmitCalleeWrittenPointerPostCall(
          inner_param, absl::Substitute("$0[sapi_i]", param.name),
          absl::Substitute("sapi_ptrs_$0[sapi_i]", param.name), "    ",
          post_call);
      absl::StrAppend(&post_call, "  }\n");
    }
  }

  if (has_leaf_out) {
    absl::SubstituteAndAppend(
        &post_call,
        "  for (sapi::v::Var* sapi_out_var : sapi_sync_out_$0) {\n"
        "    sandbox->Check(sandbox->TransferFromSandboxee(sapi_out_var));\n"
        "  }\n",
        param.name);
  }
}

void EmitHostSrcParam(const ir::Parameter& param, std::string& pre_call,
                      std::string& call_args, std::string& post_call) {
  std::visit(
      absl::Overload{
          [&](const ir::CallbackParam& cb) {
            absl::StrAppend(&pre_call, EmitCallbackHostPreCall(param, cb));
            if (cb.typedef_name.has_value() &&
                !cb.functor_template_name.has_value()) {
              absl::StrAppend(
                  &call_args,
                  absl::Substitute("$0 == nullptr ? nullptr : &sapi_cb_$0",
                                   param.name));
            } else {
              absl::StrAppend(
                  &call_args,
                  absl::Substitute(
                      "sapi_cb_$0 ? sapi_cb_$0->PtrBefore() : nullptr",
                      param.name));
            }
            if (NeedsCallbackLambdaWrapper(cb) &&
                !(cb.typedef_name.has_value() &&
                  !cb.functor_template_name.has_value()) &&
                CallbackReturnsPointer(cb) && cb.return_value->IsOutput() &&
                !(cb.return_value->type.pointee != nullptr &&
                  cb.return_value->type.pointee->is_const)) {
              absl::SubstituteAndAppend(
                  &post_call,
                  "  for (auto& var : sapi_cb_ret_vars_$0) {\n"
                  "    "
                  "sandbox->Check(sandbox->TransferFromSandboxee(var."
                  "get()));\n"
                  "  }\n",
                  param.name);
            }
          },
          [&](const ir::CppStringParam& str) {
            if (str.form == ir::CppStringParam::Form::kView ||
                str.form == ir::CppStringParam::Form::kValue ||
                (str.form == ir::CppStringParam::Form::kReference &&
                 str.is_const)) {
              absl::StrAppend(
                  &pre_call,
                  absl::Substitute("  sapi::v::Array<char> "
                                   "sapi_tmp_$0(const_cast<char*>($0.data()), "
                                   "$0.size());\n",
                                   param.name));
              absl::StrAppend(
                  &call_args,
                  absl::Substitute("sapi_tmp_$0.PtrBefore(), $0.size()",
                                   param.name));
            } else if (str.form == ir::CppStringParam::Form::kReference) {
              absl::StrAppend(&pre_call,
                              absl::Substitute("  sapi::v::LenVal sapi_tmp_$0("
                                               "const_cast<char*>($0.data()), "
                                               "$0.size());\n",
                                               param.name));
              absl::StrAppend(
                  &call_args,
                  absl::Substitute("sapi_tmp_$0.PtrBoth()", param.name));
              absl::SubstituteAndAppend(
                  &post_call,
                  "  $0.resize(sapi_tmp_$0.GetDataSize());\n"
                  "  memcpy(const_cast<char*>($0.data()), "
                  "sapi_tmp_$0.GetData(), "
                  "$0.size());\n",
                  param.name);
            } else {
              // kPointer
              absl::StrAppend(
                  &pre_call,
                  absl::Substitute(
                      "  std::unique_ptr<sapi::v::LenVal> sapi_tmp_$0;\n"
                      "  if ($0 != nullptr) {\n"
                      "    sapi_tmp_$0 = "
                      "std::make_unique<sapi::v::LenVal>("
                      "$0->data(), "
                      "$0->size());\n"
                      "  }\n",
                      param.name));
              absl::StrAppend(
                  &call_args,
                  absl::Substitute(
                      "sapi_tmp_$0 ? sapi_tmp_$0->PtrBoth() : nullptr",
                      param.name));
              absl::SubstituteAndAppend(
                  &post_call,
                  "  if ($0 != nullptr && sapi_tmp_$0) {\n"
                  "    $0->assign("
                  "reinterpret_cast<char*>(sapi_tmp_$0->GetData()), "
                  "sapi_tmp_$0->GetDataSize());\n"
                  "  }\n",
                  param.name);
            }
          },
          [&](const ir::OpaquePointerParam& op) {
            if (op.host_opaque_handle.has_value()) {
              absl::StrAppend(
                  &pre_call,
                  absl::Substitute(
                      "  sapi::v::RemotePtr sapi_tmp_$0($0 == nullptr ? "
                      "nullptr : reinterpret_cast<void*>($1));\n",
                      param.name, *op.host_opaque_handle));
            } else {
              absl::StrAppend(
                  &pre_call,
                  absl::Substitute("  sapi::v::RemotePtr sapi_tmp_$0($0);\n",
                                   param.name));
            }
            absl::StrAppend(
                &call_args,
                absl::Substitute("$0 == nullptr ? nullptr : &sapi_tmp_$0",
                                 param.name));
          },
          [&](const ir::StructSyncParam& sync) {
            std::string struct_type =
                param.type.unqualified_pointee_type_name();
            absl::StrAppend(
                &pre_call,
                absl::Substitute(
                    "  sapi::v::Struct<$0> sapi_tmp_$1($1 != nullptr ? *$1 "
                    ": ($0){});\n",
                    struct_type, param.name));
            if (!sync.members.empty() || !sync.callbacks.empty()) {
              absl::StrAppend(&pre_call,
                              EmitStructMemberSyncsPreCall(param, sync));
            }
            std::string ptr_access =
                (param.direction() == PointerDir::kIn)
                    ? "PtrBefore()"
                    : ((param.direction() == PointerDir::kOut) ? "PtrAfter()"
                                                               : "PtrBoth()");
            absl::StrAppend(
                &call_args,
                absl::Substitute("$0 == nullptr ? nullptr : sapi_tmp_$0.$1",
                                 param.name, ptr_access));
            if (!sync.members.empty() || !sync.callbacks.empty()) {
              std::string save_ptrs;
              std::string restore_ptrs;
              for (const auto& s : sync.members) {
                // Allow the sandbox to modify sandbox opaque members, and
                // don't restore them.
                if (s.direction == PointerDir::kSandboxOpaque) continue;
                std::string member_terminal =
                    s.member_name.empty() ? s.access_path() : s.member_name;
                std::string suffix =
                    absl::StrCat(param.name, "_", member_terminal);
                std::string host_ptr_expr = s.access_path();
                absl::SubstituteAndAppend(
                    &save_ptrs, "    const auto sapi_host_ptr_$0 = $1;\n",
                    suffix, host_ptr_expr);
                absl::SubstituteAndAppend(&restore_ptrs,
                                          "    if ($0 != nullptr) {\n"
                                          "      $0 = sapi_host_ptr_$1;\n"
                                          "    }\n",
                                          host_ptr_expr, suffix);
              }
              for (const auto& cb_field : sync.callbacks) {
                absl::SubstituteAndAppend(
                    &restore_ptrs,
                    "    $0->$1 = reinterpret_cast<decltype($0->$1)>(\n"
                    "        $2(reinterpret_cast<uintptr_t>(\n"
                    "            sapi_tmp_$0.data().$1)));\n",
                    param.name, cb_field.member_name,
                    BindThunkName(cb_field.typedef_name));
              }
              if (param.direction() != PointerDir::kIn &&
                  !param.type.is_const &&
                  !(param.type.pointee && param.type.pointee->is_const)) {
                absl::SubstituteAndAppend(
                    &post_call,
                    "  if ($0 != nullptr) {\n"
                    "    // Save original host pointers\n"
                    "$1"
                    "    // Sync post-call sandbox data to the struct\n"
                    "    if ($0 != nullptr) {\n"
                    "      *$0 = sapi_tmp_$0.data();\n"
                    "    }\n"
                    "    // Restore original host pointers\n"
                    "$2"
                    "  }\n",
                    param.name, save_ptrs, restore_ptrs);
              }
              absl::StrAppend(&post_call,
                              EmitStructMemberSyncsPostCall(param, sync));
            } else if (param.direction() == PointerDir::kOut ||
                       param.direction() == PointerDir::kInOut) {
              absl::StrAppend(&post_call,
                              absl::Substitute("  if ($0 != nullptr) {\n"
                                               "    *$0 = sapi_tmp_$0.data();\n"
                                               "  }\n",
                                               param.name));
            }
          },
          [&](const ir::BufferParam& buf) {
            if (buf.pointee != nullptr) {
              EmitMultiLevelPointerParam(param, buf, pre_call, call_args,
                                         post_call);
              return;
            }
            if (UsesCStringEmission(param, buf)) {
              if (buf.direction == PointerDir::kIn) {
                absl::StrAppend(
                    &pre_call,
                    absl::Substitute("  sapi::v::ConstCStr sapi_tmp_$0($0);\n",
                                     param.name));
                absl::StrAppend(
                    &call_args,
                    absl::Substitute("sapi_tmp_$0.PtrBefore()", param.name));
              } else if (buf.direction == PointerDir::kOut &&
                         std::holds_alternative<ir::lifetime::SandboxGlobal>(
                             buf.lifetime)) {
                absl::StrAppend(&pre_call,
                                absl::Substitute("  sapi::v::Reg<const char*> "
                                                 "sapi_tmp_$0(nullptr);\n",
                                                 param.name));
                absl::StrAppend(
                    &call_args,
                    absl::Substitute("sapi_tmp_$0.PtrAfter()", param.name));
                absl::SubstituteAndAppend(
                    &post_call,
                    "  if ($0 != nullptr) {\n"
                    "    *$0 = "
                    "sapi::lwbox::GlobalStringRegistry::Instance()"
                    "->GetOrFetch(*sandbox, sapi_tmp_$0.GetValue());\n"
                    "  }\n",
                    param.name);
              } else if (buf.direction == PointerDir::kInOut &&
                         std::holds_alternative<ir::lifetime::SandboxGlobal>(
                             buf.lifetime)) {
                absl::SubstituteAndAppend(
                    &pre_call,
                    R"(  std::unique_ptr<sapi::v::ConstCStr> sapi_cstr_$0;
  const char* remote_$0 = nullptr;
  if ($0 != nullptr && *$0 != nullptr) {
    sapi_cstr_$0 = std::make_unique<sapi::v::ConstCStr>(*$0);
    sandbox->Check(sandbox->Allocate(sapi_cstr_$0.get(),
                   /*automatic_free=*/true));
    sandbox->Check(sandbox->TransferToSandboxee(sapi_cstr_$0.get()));
    remote_$0 = reinterpret_cast<const char*>(sapi_cstr_$0->GetRemote());
  }
  sapi::v::Reg<const char*> sapi_tmp_$0(remote_$0);
)",
                    param.name);
                absl::StrAppend(
                    &call_args,
                    absl::Substitute("sapi_tmp_$0.PtrBoth()", param.name));
                absl::SubstituteAndAppend(
                    &post_call,
                    "  if ($0 != nullptr) {\n"
                    "    *$0 = "
                    "sapi::lwbox::GlobalStringRegistry::Instance()"
                    "->GetOrFetch(*sandbox, sapi_tmp_$0.GetValue());\n"
                    "  }\n",
                    param.name);
              }
              return;
            }
            if (buf.context_bound.copy_from_and_bind.has_value()) {
              std::string pointee_type =
                  param.type.unqualified_pointee_type_name();
              absl::StrAppend(
                  &pre_call,
                  absl::Substitute("  sapi::v::Reg<$0> sapi_tmp_$1(nullptr);\n",
                                   pointee_type, param.name));
              std::string ptr_access =
                  (buf.direction == PointerDir::kIn)
                      ? "PtrBefore()"
                      : ((buf.direction == PointerDir::kOut) ? "PtrAfter()"
                                                             : "PtrBoth()");
              absl::StrAppend(
                  &call_args,
                  absl::Substitute("$0 == nullptr ? nullptr : sapi_tmp_$0.$1",
                                   param.name, ptr_access));
              absl::StrAppend(&post_call,
                              EmitCopyFromAndBindOutPtrCode(
                                  *buf.context_bound.copy_from_and_bind,
                                  absl::StrCat("sapi_tmp_", param.name),
                                  pointee_type, buf.bounds));
              absl::SubstituteAndAppend(&post_call,
                                        "  if ($0 != nullptr) {\n"
                                        "    *$0 = sapi_tmp_$0.GetValue();\n"
                                        "  }\n",
                                        param.name);
            } else if (param.type.is_pointee_record() &&
                       !buf.context_bound.retain_and_bind.has_value() &&
                       std::holds_alternative<ir::bounds::Singleton>(
                           buf.bounds)) {
              // Single unannotated struct pointers (`Singleton`) use
              // `sapi::v::Struct<T>`, which owns a stack-allocated `T`
              // value (`sapi_tmp_<param>.data()`) initialized from
              // `*<param>` (or `{}` when `<param> == nullptr`) and writes
              // back `*<param> = sapi_tmp_<param>.data()` on
              // `kOut`/`kInOut`.
              //
              // All explicitly sized or retained struct buffers
              // (`ElemCount`, `ByteCount`, `SizedByBinding`,
              // `*SizedByOutparam`, `retain_and_bind`) intentionally fall
              // through to the generic `sapi::v::Array<char>` byte-buffer
              // path below rather than emitting `sapi::v::Array<T>`. See
              // the comment on `sapi::v::Array<char>` below for why this is
              // both overflow-safe and well-defined in C++.
              std::string struct_type =
                  param.type.unqualified_pointee_type_name();
              absl::StrAppend(
                  &pre_call,
                  absl::Substitute(
                      "  sapi::v::Struct<$0> sapi_tmp_$1($1 != nullptr ? "
                      "*$1 : ($0){});\n",
                      struct_type, param.name));
              std::string ptr_access =
                  (param.direction() == PointerDir::kIn)
                      ? "PtrBefore()"
                      : ((param.direction() == PointerDir::kOut) ? "PtrAfter()"
                                                                 : "PtrBoth()");
              absl::StrAppend(
                  &call_args,
                  absl::Substitute("$0 == nullptr ? nullptr : sapi_tmp_$0.$1",
                                   param.name, ptr_access));
              if (param.direction() == PointerDir::kOut ||
                  param.direction() == PointerDir::kInOut) {
                absl::StrAppend(
                    &post_call,
                    absl::Substitute("  if ($0 != nullptr) {\n"
                                     "    *$0 = sapi_tmp_$0.data();\n"
                                     "  }\n",
                                     param.name));
              }
            } else {
              std::string cap_expr = GetParamCapacityAsBytesExpr(param, buf);
              std::string size_expr = GetParamSizeAsBytesExpr(param, buf);
              bool is_deref_outparam = IsSizeBasedOnDerefOutParam(buf);

              if (buf.context_bound.retain_and_bind.has_value()) {
                absl::SubstituteAndAppend(
                    &pre_call,
                    "  sapi::v::RemotePtr sapi_tmp_$0(nullptr);\n"
                    "  if ($0 != nullptr) {\n"
                    "    void* sapi_sb_ptr = nullptr;\n"
                    "    sandbox->Check(\n"
                    "        sandbox->rpc_channel()->Allocate("
                    "$1, &sapi_sb_ptr));\n"
                    "    sapi_tmp_$0 = sapi::v::RemotePtr(sapi_sb_ptr);\n"
                    "  }\n",
                    param.name, cap_expr);
                if (param.direction() == PointerDir::kIn ||
                    param.direction() == PointerDir::kInOut) {
                  absl::SubstituteAndAppend(
                      &pre_call,
                      "  if ($0 != nullptr) {\n"
                      "    sandbox->Check(\n"
                      "        sandbox->rpc_channel()\n"
                      "            ->CopyToSandbox("
                      "sapi_tmp_$0.GetRemoteValue(),\n"
                      "                            "
                      "absl::MakeSpan(reinterpret_cast<const char*>($0),\n"
                      "                                           $1))\n"
                      "            .status());\n"
                      "  }\n",
                      param.name, cap_expr);
                }
                absl::StrAppend(
                    &call_args,
                    absl::Substitute("$0 == nullptr ? nullptr : &sapi_tmp_$0",
                                     param.name));

                if (param.direction() == PointerDir::kOut ||
                    param.direction() == PointerDir::kInOut) {
                  absl::SubstituteAndAppend(
                      &post_call,
                      "  if (sapi_tmp_$0.GetRemoteValue() != 0) {\n"
                      "    sapi::lwbox::SyncFromSandboxToHost(\n"
                      "        *sandbox, sapi_tmp_$0.GetRemoteValue(),\n"
                      "        reinterpret_cast<void*>($0), $1);\n"
                      "  }\n",
                      param.name, cap_expr);
                }
              } else {
                // Wrap every non-retained buffer (scalars, void*, and
                // sized struct arrays) in `sapi::v::Array<char>` with the
                // byte capacity `cap_expr` rather than `sapi::v::Array<T>`:
                //
                // 1. Overflow safety: `sapi::v::Array<T>(T*, size_t nelem)`
                //    computes `total_size_ = nelem * sizeof(T)` with an
                //    unchecked `*`. Routing `ElemCount` through `cap_expr`
                //    emits `sandbox->CheckedMultiply(sizeof(*p), (nelem))`
                //    so integer overflow traps via `CHECK` before
                //    allocating or copying.
                // 2. Strict aliasing & object representation:
                //    `arg_converter.cc` enforces that buffer pointees are
                //    trivially copyable (`IsDeeplyTriviallyCopyableType`).
                //    Under C++ [basic.lval] and [basic.types.general], any
                //    trivially copyable `T[N]` object representation can be
                //    accessed and copied through `char*` / `const char*`
                //    without violating strict aliasing.
                // 3. `const_cast` safety: `sapi::v::Array<const T>` already
                //    performs `SetLocal(const_cast<T*>(arr_))` internally
                //    to store `void*` in `sapi::v::Var`. Casting away
                //    `const` on the pointer is well-defined
                //    ([expr.const.cast]) because `const` buffers have
                //    `PointerDir::kIn`
                //    (`PtrBefore()`), which only reads `[GetLocal(),
                //    GetLocal() + GetSize())` via `CopyToSandbox` and never
                //    writes through the pointer.
                // 4. Sandboxee alignment: `sapi::v::Var::Allocate` passes
                //    only the byte count `GetSize()` to
                //    `rpc_channel()->Allocate`, which calls `malloc(size)`
                //    in the sandboxee (`alignof(std::max_align_t)`),
                //    independent of `Array`'s element type `T`.
                absl::StrAppend(
                    &pre_call,
                    absl::Substitute(
                        "  sapi::v::Array<char> "
                        "sapi_tmp_$0(const_cast<char*>(reinterpret_cast<"
                        "const char*>($0)), $1);\n",
                        param.name, cap_expr));
              }

              if (is_deref_outparam) {
                absl::StrAppend(
                    &pre_call,
                    absl::Substitute(
                        "  if ($0 != nullptr) {\n"
                        "    "
                        "sandbox->Check(sandbox->Allocate(&sapi_tmp_$0, "
                        "/*automatic_free=*/true));\n"
                        "  }\n",
                        param.name));
                if (param.direction() == PointerDir::kInOut ||
                    param.direction() == PointerDir::kIn) {
                  absl::StrAppend(
                      &pre_call,
                      absl::Substitute(
                          "  if ($0 != nullptr) {\n"
                          "    "
                          "sandbox->Check("
                          "sandbox->rpc_channel()->CopyToSandbox(\n"
                          "        "
                          "reinterpret_cast<uintptr_t>("
                          "sapi_tmp_$0.GetRemote()),\n"
                          "        absl::MakeSpan(reinterpret_cast<const "
                          "char*>($0), "
                          "$1)).status());\n"
                          "  }\n",
                          param.name, size_expr));
                }
                absl::StrAppend(
                    &call_args,
                    absl::Substitute(
                        "$0 == nullptr ? nullptr : sapi_tmp_$0.PtrNone()",
                        param.name));
                absl::StrAppend(
                    &post_call,
                    absl::Substitute(
                        "  if ($0 != nullptr) {\n"
                        "    size_t sapi_final_size = $1;\n"
                        "    size_t sapi_cap_size = $2;\n"
                        "    if (sapi_final_size > sapi_cap_size) {\n"
                        "      sandbox->Check(absl::OutOfRangeError(\n"
                        "          absl::StrCat(\"Sandboxee returned size "
                        "(\", sapi_final_size,\n"
                        "                       \") exceeding capacity "
                        "(\", "
                        "sapi_cap_size, \") for param $0\")));\n"
                        "    }\n"
                        "    sandbox->Check(\n"
                        "        sandbox->rpc_channel()\n"
                        "            ->CopyFromSandbox(\n"
                        "                "
                        "reinterpret_cast<uintptr_t>(sapi_tmp_$0."
                        "GetRemote()),\n"
                        "                "
                        "absl::MakeSpan("
                        "reinterpret_cast<char*>($0), sapi_final_size))\n"
                        "            .status());\n"
                        "  }\n",
                        param.name, size_expr, cap_expr));
              } else if (!buf.context_bound.retain_and_bind.has_value()) {
                std::string ptr_access =
                    (param.direction() == PointerDir::kIn)
                        ? "PtrBefore()"
                        : ((param.direction() == PointerDir::kOut)
                               ? "PtrAfter()"
                               : "PtrBoth()");
                absl::StrAppend(
                    &call_args,
                    absl::Substitute("$0 == nullptr ? nullptr : sapi_tmp_$0.$1",
                                     param.name, ptr_access));
              }
            }

            if (buf.context_bound.retain_and_bind.has_value() &&
                param.type.is_pointer()) {
              std::string ctx_name = ResolveContextName(
                  buf.context_bound.retain_and_bind->context);
              std::string cap_expr = GetParamCapacityAsBytesExpr(param, buf);
              absl::SubstituteAndAppend(
                  &post_call,
                  "  if (sapi_tmp_$0.GetRemoteValue() != 0 && $1 != "
                  "nullptr) "
                  "{\n"
                  "    "
                  "sapi::lwbox::ContextBindingRegistry::Instance()->"
                  "RetainPointer(\n"
                  "        $1, \"$2\", sapi_tmp_$0.GetRemoteValue(), $3);\n"
                  "  }\n",
                  param.name, ctx_name,
                  buf.context_bound.retain_and_bind->binding_name, cap_expr);
            }
          },
          [&](const auto& p) {
            using T = std::decay_t<decltype(p)>;
            static_assert(
                IsOneOf<T, ir::VoidParam, ir::ScalarParam,
                        ir::SandboxeeCallbackParam>,
                "Unhandled parameter payload type in host call args!");
            absl::StrAppend(&call_args, param.name);
          },
      },
      param.payload);
}

absl::flat_hash_set<std::string> GatherHostIncludes(
    const ir::Library& library,
    absl::Span<const ir::Function* const> sorted_funcs,
    const absl::flat_hash_set<std::string>& includes) {
  absl::flat_hash_set<std::string> host_includes = includes;
  host_includes.insert(absl::Substitute(
      "\"$0sandboxed_api/lwbox/runtime/lwbox_runtime.h\"", kIncludePrefix));
  if (HasStringType(library)) {
    host_includes.insert(
        absl::Substitute("\"$0sandboxed_api/lenval_core.h\"", kIncludePrefix));
  }
  for (const auto* func : sorted_funcs) {
    if (func->invoker_for_typedef) {
      host_includes.insert("<cstdint>");
      host_includes.insert("<optional>");
      host_includes.insert(
          absl::Substitute("\"$0absl/log/check.h\"", kIncludePrefix));
      host_includes.insert(
          absl::Substitute("\"$0absl/status/statusor.h\"", kIncludePrefix));
      for (size_t i = 1; i < func->parameters.size(); ++i) {
        if (const auto* buf = func->parameters[i].As<ir::BufferParam>()) {
          if (buf->pointee != nullptr) {
            host_includes.insert("<algorithm>");
            host_includes.insert("<cstdint>");
            host_includes.insert("<memory>");
            host_includes.insert("<vector>");
          } else if (UsesCStringEmission(func->parameters[i], *buf)) {
            host_includes.insert("<string>");
            host_includes.insert("<cstring>");
          } else if (std::holds_alternative<ir::bounds::NullTerminated>(
                         buf->bounds)) {
            host_includes.insert("<vector>");
          }
        }
      }
    }
    if (func->return_value.has_value()) {
      if (const auto* ret_buf = func->return_value->As<ir::BufferParam>();
          ret_buf != nullptr &&
          ret_buf->context_bound.copy_from_and_bind.has_value() &&
          std::holds_alternative<ir::bounds::NullTerminated>(ret_buf->bounds)) {
        host_includes.insert("<cstdlib>");
        host_includes.insert("<cstring>");
        host_includes.insert("<vector>");
      }
    }
    for (const auto& param : func->parameters) {
      std::visit(
          absl::Overload{
              [&](const ir::CallbackParam& cb) {
                host_includes.insert("<optional>");
                host_includes.insert(absl::Substitute(
                    "\"$0sandboxed_api/var_callback.h\"", kIncludePrefix));
                if (cb.functor_template_name.has_value()) {
                  if (*cb.functor_template_name == "std::function") {
                    host_includes.insert("<functional>");
                  } else if (*cb.functor_template_name ==
                             "absl::AnyInvocable") {
                    host_includes.insert(absl::Substitute(
                        "\"$0absl/functional/any_invocable.h\"",
                        kIncludePrefix));
                  }
                }
                if (NeedsCallbackLambdaWrapper(cb)) {
                  if (CallbackReturnsPointer(cb)) {
                    host_includes.insert("<vector>");
                    host_includes.insert("<memory>");
                  }
                  if (cb.is_callback_return_aliased) {
                    host_includes.insert(
                        absl::Substitute("\"$0absl/container/flat_hash_map.h\"",
                                         kIncludePrefix));
                  }
                  for (const auto& cb_p : cb.callback_parameters) {
                    std::visit(
                        absl::Overload{
                            [&](const ir::BufferParam& cb_buf) {
                              if (cb_buf.pointee != nullptr) {
                                host_includes.insert("<algorithm>");
                                host_includes.insert("<cstdint>");
                                host_includes.insert("<vector>");
                              } else if (UsesCStringEmission(cb_p, cb_buf)) {
                                host_includes.insert("<string>");
                                host_includes.insert("<cstring>");
                              } else if (std::holds_alternative<
                                             ir::bounds::NullTerminated>(
                                             cb_buf.bounds)) {
                                host_includes.insert("<vector>");
                                host_includes.insert("<cstdint>");
                              }
                            },
                            [&](const auto& p) {
                              using T = std::decay_t<decltype(p)>;
                              static_assert(
                                  IsOneOf<T, ir::VoidParam, ir::ScalarParam,
                                          ir::CppStringParam,
                                          ir::OpaquePointerParam,
                                          ir::StructSyncParam,
                                          ir::CallbackParam,
                                          ir::SandboxeeCallbackParam>,
                                  "Unhandled callback parameter payload type "
                                  "in includes check!");
                            },
                        },
                        cb_p.payload);
                  }
                }
              },
              [&](const ir::BufferParam& buf) {
                if (buf.pointee != nullptr) {
                  host_includes.insert("<algorithm>");
                  host_includes.insert("<memory>");
                  host_includes.insert("<vector>");
                  if (const auto* inner_buf =
                          buf.pointee->As<ir::BufferParam>();
                      inner_buf != nullptr &&
                      inner_buf->context_bound.copy_from_and_bind.has_value() &&
                      std::holds_alternative<ir::bounds::NullTerminated>(
                          inner_buf->bounds)) {
                    host_includes.insert("<cstdlib>");
                    host_includes.insert("<cstring>");
                  }
                } else if (buf.context_bound.copy_from_and_bind.has_value() &&
                           std::holds_alternative<ir::bounds::NullTerminated>(
                               buf.bounds)) {
                  host_includes.insert("<cstdlib>");
                  host_includes.insert("<cstring>");
                  host_includes.insert("<vector>");
                }
              },
              [&](const auto& p) {
                using T = std::decay_t<decltype(p)>;
                static_assert(
                    IsOneOf<T, ir::VoidParam, ir::ScalarParam,
                            ir::CppStringParam, ir::OpaquePointerParam,
                            ir::StructSyncParam, ir::SandboxeeCallbackParam>,
                    "Unhandled parameter payload in GatherHostIncludes!");
              },
          },
          param.payload);
    }
  }
  return host_includes;
}

// Number of host thunks emitted per callback typedef.
//
// Each thunk is a distinct function symbol with the callback typedef's C
// signature, because a C caller passes no extra closure argument and the thunk
// can only identify its target sandboxee function from its own code address.
// 32 slots per typedef (~640 bytes of code and 32 pointers) cover libraries
// that expose multiple internal callbacks; exceeding the pool aborts with a
// clear diagnostic rather than silently reusing a slot.
//
// TODO(b/584178307): Avoid fixed-size thunk pool exhaustion (for example, by
// sizing pools via static analysis or an explicit annotation).
constexpr int kThunkPoolSize = 32;

// Emits one callback typedef's host thunks: `kThunkPoolSize` functions carrying
// the typedef's signature, the dispatcher they share, the pool that names them,
// and the entry point that binds a sandboxee function to a free slot.
//
// The pools are emitted after the host shims: a thunk calls the shim for its
// callback typedef's invoker, and a shim that hands a callback back out calls
// this entry point, so the two refer to each other.
std::string EmitThunkPool(const ir::Function& invoker) {
  const std::string& typedef_name = *invoker.invoker_for_typedef;
  const std::string ret_type =
      invoker.return_value ? invoker.return_value->type.canonical_name : "void";

  // A thunk has the callback typedef's signature, which is the invoker's
  // without its leading target parameter.
  std::vector<std::string> param_decls;
  std::vector<std::string> arg_names;
  param_decls.reserve(invoker.parameters.size() - 1);
  arg_names.reserve(invoker.parameters.size() - 1);
  for (size_t i = 1; i < invoker.parameters.size(); ++i) {
    param_decls.push_back(EmitHostParamDecl(invoker.parameters[i]));
    arg_names.push_back(invoker.parameters[i].name);
  }
  const std::string params = absl::StrJoin(param_decls, ", ");
  const std::string args = absl::StrJoin(arg_names, ", ");
  const std::string args_after_target =
      args.empty() ? "" : absl::StrCat(", ", args);

  std::string out;
  absl::SubstituteAndAppend(
      &out,
      "// Host thunks for callback typedef `$0`.\n"
      "//\n"
      "// Each carries the typedef's signature, so library code cannot tell\n"
      "// one from a function the host wrote. A thunk recovers which "
      "sandboxee\n"
      "// function it stands in for from its own address, which is all it "
      "has:\n"
      "// it is called through the library's signature, so there is no spare\n"
      "// argument to carry a slot index.\n"
      "extern \"C\" const sapi::lwbox::ThunkPool* sapi_thunk_pool_$0();\n\n"
      "namespace {\n\n"
      "$1 sapi_dispatch_thunk_$0(uintptr_t sapi_thunk$2) {\n"
      "  std::optional<uintptr_t> sapi_bound =\n"
      "      sapi::lwbox::SandboxeeCallbackRegistry::Instance()->LookUpThunk(\n"
      "          ::sapi::lwbox::SharedSandboxInstance("
      "&CreateMergedSandboxConfig),\n"
      "          *sapi_thunk_pool_$0(), sapi_thunk);\n"
      "  CHECK(sapi_bound.has_value())\n"
      "      << \"a host thunk for callback typedef $0 was called after its "
      "\"\n"
      "         \"binding was released\";\n"
      "  return $3(*sapi_bound$4);\n"
      "}\n\n",
      typedef_name, ret_type, params.empty() ? "" : absl::StrCat(", ", params),
      invoker.name, args_after_target);

  std::vector<std::string> thunk_addresses;
  thunk_addresses.reserve(kThunkPoolSize);
  for (int i = 0; i < kThunkPoolSize; ++i) {
    std::string thunk_name =
        absl::Substitute("sapi_thunk_$0_$1", typedef_name, i);
    absl::SubstituteAndAppend(&out,
                              "$0 $1($2) {\n"
                              "  return sapi_dispatch_thunk_$3(\n"
                              "      reinterpret_cast<uintptr_t>(&$1)$4);\n"
                              "}\n\n",
                              ret_type, thunk_name, params, typedef_name,
                              args_after_target);
    thunk_addresses.push_back(absl::Substitute(
        "      reinterpret_cast<uintptr_t>(&$0),", thunk_name));
  }

  absl::Span<const ir::Parameter> typedef_params =
      absl::MakeConstSpan(invoker.parameters).subspan(1);
  std::vector<std::string> lambda_params;
  std::vector<std::string> lambda_call_args;
  std::vector<std::string> pre_call_blocks;
  std::string param_sync_post_call;
  EmitCallbackParamMarshaling(typedef_params, lambda_params, lambda_call_args,
                              pre_call_blocks, param_sync_post_call);
  std::string param_sync_pre_call;
  if (!pre_call_blocks.empty()) {
    param_sync_pre_call =
        absl::StrCat(absl::StrJoin(pre_call_blocks, "\n\n"), "\n\n");
  }
  std::string lambda_call_str = absl::StrJoin(lambda_call_args, ", ");
  std::string lambda_body;
  if (ret_type == "void") {
    if (param_sync_post_call.empty()) {
      lambda_body = absl::Substitute(
          "$0      reinterpret_cast<CallbackFn>(sapi_host_fn)($1);\n",
          param_sync_pre_call, lambda_call_str);
    } else {
      lambda_body = absl::Substitute(
          "$0      reinterpret_cast<CallbackFn>(sapi_host_fn)($1);\n\n$2",
          param_sync_pre_call, lambda_call_str, param_sync_post_call);
    }
  } else {
    if (param_sync_post_call.empty()) {
      lambda_body = absl::Substitute(
          "$0      $1 sapi_cb_ret = "
          "reinterpret_cast<CallbackFn>(sapi_host_fn)($2);\n"
          "      return sapi_cb_ret;\n",
          param_sync_pre_call, ret_type, lambda_call_str);
    } else {
      lambda_body = absl::Substitute(
          "$0      $1 sapi_cb_ret = "
          "reinterpret_cast<CallbackFn>(sapi_host_fn)($2);\n\n"
          "$3      return sapi_cb_ret;\n",
          param_sync_pre_call, ret_type, lambda_call_str, param_sync_post_call);
    }
  }

  std::string idempotent_arg =
      invoker.is_idempotent_typedef ? ", /*idempotent=*/true" : "";
  absl::SubstituteAndAppend(
      &out,
      "}  // namespace\n\n"
      "extern \"C\" const sapi::lwbox::ThunkPool* sapi_thunk_pool_$0() {\n"
      "  static const uintptr_t kThunks[] = {\n"
      "$1\n"
      "  };\n"
      "  static const sapi::lwbox::ThunkPool kPool = {\"$0\", kThunks};\n"
      "  return &kPool;\n"
      "}\n\n"
      "// Returns the host-callable stand-in for a sandboxee function with\n"
      "// callback typedef `$0`'s signature. A null function stays null, and "
      "a\n"
      "// trampoline that stands in for one of our own host callbacks unwraps\n"
      "// back to that host function after verifying that it was registered\n"
      "// under callback typedef `$0`.\n"
      "extern \"C\" uintptr_t sapi_bind_thunk_$0(uintptr_t sapi_sandboxee_fn) "
      "{\n"
      "  auto* sandbox = &::sapi::lwbox::SharedSandboxInstance("
      "&CreateMergedSandboxConfig);\n"
      "  if (std::optional<uintptr_t> sapi_host_fn =\n"
      "          sapi::lwbox::HostCallbackRegistry::Instance()"
      "->LookUpTrampoline(\n"
      "              *sandbox, \"$0\", sapi_sandboxee_fn);\n"
      "      sapi_host_fn.has_value()) {\n"
      "    return *sapi_host_fn;\n"
      "  }\n"
      "  absl::StatusOr<uintptr_t> sapi_thunk =\n"
      "      sapi::lwbox::SandboxeeCallbackRegistry::Instance()->ThunkFor(\n"
      "          *sandbox, *sapi_thunk_pool_$0(), sapi_sandboxee_fn);\n"
      "  sandbox->Check(sapi_thunk.status());\n"
      "  return *sapi_thunk;\n"
      "}\n\n"
      "// Returns the sandboxee-callable stand-in for a host function with\n"
      "// callback typedef `$0`'s signature. A null function stays null, and "
      "a\n"
      "// host thunk that stands in for a sandboxee function unwraps back to "
      "that\n"
      "// sandboxee function after verifying its thunk pool.\n"
      "extern \"C\" uintptr_t sapi_register_callback_$0(\n"
      "    uintptr_t sapi_host_fn) {\n"
      "  auto* sandbox = &::sapi::lwbox::SharedSandboxInstance("
      "&CreateMergedSandboxConfig);\n"
      "  if (std::optional<uintptr_t> sapi_bound =\n"
      "          sapi::lwbox::SandboxeeCallbackRegistry::Instance()"
      "->LookUpThunk(\n"
      "              *sandbox, *sapi_thunk_pool_$0(), sapi_host_fn);\n"
      "      sapi_bound.has_value()) {\n"
      "    return *sapi_bound;\n"
      "  }\n"
      "  using CallbackFn = $2;\n"
      "  absl::StatusOr<uintptr_t> sapi_trampoline =\n"
      "      sapi::lwbox::HostCallbackRegistry::Instance()->TrampolineFor(\n"
      "          *sandbox, \"$0\", sapi_host_fn,\n"
      "          [sandbox, sapi_host_fn]($3) -> $4 {\n"
      "$5          }$6);\n"
      "  sandbox->Check(sapi_trampoline.status());\n"
      "  return *sapi_trampoline;\n"
      "}\n\n",
      typedef_name, absl::StrJoin(thunk_addresses, "\n"),
      EmitInvokerTargetType(invoker), absl::StrJoin(lambda_params, ", "),
      ret_type, lambda_body, idempotent_arg);
  return out;
}

}  // namespace
absl::StatusOr<std::string> EmitHostSrc(
    const GeneratorOptions& options, const ir::Library& library,
    const absl::flat_hash_set<std::string>& includes) {
  std::string out;
  absl::StrAppendFormat(&out, "#include \"%s\"\n", options.out_file);
  absl::StrAppend(&out, absl::Substitute(kHostHeader, kIncludePrefix));

  std::vector<const ir::Function*> sorted_funcs = GetSortedFunctions(library);

  if (library.host_code) {
    absl::StrAppend(&out, *library.host_code, "\n\n");
  }

  for (const auto& src : library.host_state_vars) {
    absl::StrAppend(&out, src, "\n");
  }

  // The pools are emitted after the shims, because a thunk calls the shim for
  // its callback typedef's invoker. A shim that hands a callback in or back out
  // calls the pool's entry points, so those have to be declared first.
  std::string bind_decls;
  for (const auto* func : sorted_funcs) {
    if (func->invoker_for_typedef) {
      absl::SubstituteAndAppend(
          &bind_decls,
          "extern \"C\" uintptr_t $0(uintptr_t sapi_sandboxee_fn);\n"
          "extern \"C\" uintptr_t $1(uintptr_t sapi_host_fn);\n",
          BindThunkName(*func->invoker_for_typedef),
          RegisterCallbackName(*func->invoker_for_typedef));
    }
  }
  if (!bind_decls.empty()) {
    absl::StrAppend(&out, bind_decls, "\n");
  }

  for (const auto* func : sorted_funcs) {
    if (func->host_thunk) {
      absl::StrAppend(&out, "// Start of thunk\n");
      // Forward declare the sandboxee thunk, as the host thunk calls into it.
      if (func->sandboxee_thunk) {
        absl::StrAppend(&out, "extern \"C\" ",
                        func->sandboxee_thunk->declaration, ";\n");
      }
      absl::StrAppend(&out, "extern \"C\" ", func->host_thunk->body,
                      "\n// End of thunk\n\n");
      continue;
    }

    EmitFuncDecl(out, *func);
    absl::StrAppend(
        &out, " {\n",
        "  auto* sandbox = &::sapi::lwbox::SharedSandboxInstance("
        "&CreateMergedSandboxConfig);\n",
        absl::Substitute("  $0Api api(sandbox);\n\n", options.name));

    std::string pre_call;
    std::string call_args;
    std::string post_call;

    for (size_t i = 0; i < func->parameters.size(); ++i) {
      if (i > 0) absl::StrAppend(&call_args, ", ");
      EmitHostSrcParam(func->parameters[i], pre_call, call_args, post_call);
    }

    if (func->return_value) {
      if (!func->parameters.empty()) absl::StrAppend(&call_args, ", ");
      if (func->return_value->type.kind == ir::TypeKind::kString) {
        absl::StrAppend(&pre_call,
                        "  sapi::v::LenVal sapi_ret_tmp(nullptr, 0);\n");
        absl::StrAppend(&call_args, "sapi_ret_tmp.PtrAfter()");
      } else {
        absl::StrAppend(&pre_call,
                        absl::Substitute("  sapi::v::Reg<$0> sapi_ret_arg;\n",
                                         WireTypeName(*func->return_value)));
        absl::StrAppend(&call_args, "sapi_ret_arg.PtrAfter()");
      }
    }

    for (const auto& param : func->parameters) {
      if (param.should_clear_bindings()) {
        absl::SubstituteAndAppend(
            &post_call,
            "  sapi::lwbox::ContextBindingRegistry::Instance()->"
            "ClearBindings(*sandbox, $0);\n",
            param.name);
      }
    }

    absl::StrAppend(&out, pre_call, "\n");
    absl::StrAppend(&out,
                    absl::Substitute("  sandbox->Check(api.$0$1($2));\n\n",
                                     kWrapperPrefix, func->name, call_args));
    absl::StrAppend(&out, post_call);

    // Context bound post-call data binding
    for (const auto& bind : func->context_bound.bind_data) {
      std::string ctx_name = ResolveContextName(bind.context);
      absl::StrAppend(
          &out,
          absl::Substitute(
              "  if ($0 != nullptr) {\n"
              "    sapi::lwbox::ContextBindingRegistry::Instance()->BindSize(\n"
              "        $0, \"$2\", $1);\n"
              "  }\n",
              ctx_name, bind.host_computable_expr, bind.binding_name));
    }

    if (func->return_value) {
      std::visit(
          absl::Overload{
              [&](const ir::CppStringParam&) {
                absl::StrAppend(
                    &out,
                    "  return "
                    "std::string(reinterpret_cast<char*>("
                    "sapi_ret_tmp.GetData()), sapi_ret_tmp.GetDataSize());\n");
              },
              [&](const ir::BufferParam& ret_buf) {
                if (const auto* alias = std::get_if<ir::lifetime::AliasHostPtr>(
                        &ret_buf.lifetime)) {
                  absl::StrAppend(
                      &out,
                      absl::Substitute(
                          "  return sapi_ret_arg.GetValue() ? $0 : nullptr;\n",
                          alias->host_param_name));
                } else if (const auto* alias_cb =
                               std::get_if<ir::lifetime::AliasCallbackReturn>(
                                   &ret_buf.lifetime)) {
                  // Security invariant: `sapi_ret_arg.GetValue()` comes from
                  // the untrusted sandboxee and under `SANDBOX_RETURN_ALIAS`
                  // must be either nullptr or one of the remote buffers
                  // allocated on behalf of `cb` during this call. Using
                  // `operator[]` would silently default-insert `nullptr` for a
                  // forged address; `.at()` fails closed if the sandboxee
                  // returns an unaliased non-null pointer.
                  absl::SubstituteAndAppend(
                      &out,
                      "  return sapi_ret_arg.GetValue()\n"
                      "             ? static_cast<$0>(\n"
                      "                   "
                      "sapi_alias_cb_return_map_$1.at(reinterpret_cast<uintptr_"
                      "t>(\n"
                      "                       sapi_ret_arg.GetValue())))\n"
                      "             : nullptr;\n",
                      func->return_value->type.canonical_name,
                      alias_cb->callback_param_name);
                } else if (ret_buf.context_bound.copy_from_and_bind
                               .has_value()) {
                  absl::StrAppend(&out,
                                  EmitCopyFromAndBindOutPtrCode(
                                      *ret_buf.context_bound.copy_from_and_bind,
                                      "sapi_ret_arg",
                                      func->return_value->type.canonical_name,
                                      ret_buf.bounds));
                  absl::StrAppend(&out, "  return sapi_ret_arg.GetValue();\n");
                } else if (std::holds_alternative<ir::lifetime::SandboxGlobal>(
                               ret_buf.lifetime)) {
                  absl::SubstituteAndAppend(
                      &out,
                      "  return sapi::lwbox::GlobalStringRegistry::Instance()"
                      "->GetOrFetch(*sandbox, sapi_ret_arg.GetValue());\n");
                } else {
                  absl::StrAppend(&out, "  return sapi_ret_arg.GetValue();\n");
                }
              },
              [&](const ir::SandboxeeCallbackParam& cb) {
                // What arrived is an address inside the sandbox, which host
                // code cannot call. Hand back a thunk with the callback
                // typedef's signature instead; the caller cannot tell it from a
                // function the library wrote. A null callback binds to
                // nothing and stays null.
                absl::SubstituteAndAppend(
                    &out,
                    "  return reinterpret_cast<$0>($1(\n"
                    "      sapi_ret_arg.GetValue()));\n",
                    CallbackTypedefAliasName(cb.typedef_name),
                    BindThunkName(cb.typedef_name));
              },
              [&](const auto& p) {
                using T = std::decay_t<decltype(p)>;
                static_assert(
                    IsOneOf<T, ir::VoidParam, ir::ScalarParam,
                            ir::OpaquePointerParam, ir::StructSyncParam,
                            ir::CallbackParam>,
                    "Unhandled return value payload type in HostSrc!");
                absl::StrAppend(&out, "  return sapi_ret_arg.GetValue();\n");
              },
          },
          func->return_value->payload);
    }
    absl::StrAppend(&out, "}\n\n");
  }

  // After every shim, because a thunk calls the shim for its callback typedef's
  // invoker.
  for (const auto* func : sorted_funcs) {
    if (!func->invoker_for_typedef) {
      continue;
    }
    absl::StrAppend(&out, EmitThunkPool(*func));
  }

  absl::flat_hash_set<std::string> host_includes =
      GatherHostIncludes(library, sorted_funcs, includes);
  return FinalizeCode(out, /*is_header=*/false, /*add_includes=*/true,
                      host_includes);
}


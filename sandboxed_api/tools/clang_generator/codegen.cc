// Returns true if the callback returns a pointer or if any of its parameters
// are pointers or annotated buffers. In these cases, we must wrap the callback
// in a host-side lambda trampoline to perform translation, syncing, or
// tracking.
bool NeedsCallbackLambdaWrapper(const ir::CallbackParam& cb) {
  if (CallbackReturnsPointer(cb)) {
    return true;
  }
  for (const auto& p : cb.callback_parameters) {
    bool needs_wrap = std::visit(
        absl::Overload{
            [](const ir::BufferParam&) { return true; },
            [&](const auto& inner) {
              using T = std::decay_t<decltype(inner)>;
              static_assert(IsOneOf<T, ir::VoidParam, ir::ScalarParam,
                                    ir::CppStringParam, ir::OpaquePointerParam,
                                    ir::StructSyncParam, ir::CallbackParam>,
                            "Unhandled callback parameter payload in "
                            "NeedsCallbackLambdaWrapper!");
              return p.direction().has_value();
            },
        },
        p.payload);
    if (needs_wrap) return true;
  }
  return false;
}

// Computes the size in bytes for a callback return buffer.
std::string GetCallbackReturnSizeAsBytesExpr(const ir::Parameter& cb_param,
                                             const ir::CallbackParam& cb) {
  std::string ret_host_var = absl::StrCat("sapi_", cb_param.name, "_ret_host");
  const auto* ret_buf =
      cb.return_value ? cb.return_value->As<ir::BufferParam>() : nullptr;
  if (ret_buf == nullptr) {
    return absl::Substitute("sizeof(*$0)", ret_host_var);
  }
  return std::visit(
      absl::Overload{
          [&](const ir::bounds::Singleton&) {
            return absl::Substitute("sizeof(*$0)", ret_host_var);
          },
          [&](const ir::bounds::ElemCount& elem) {
            return absl::Substitute(
                "sandbox->CheckedMultiply(sizeof(*$0), ($1))", ret_host_var,
                elem.size_expr);
          },
          [](const ir::bounds::ByteCount& byte) { return byte.size_expr; },
          [&](const ir::bounds::NullTerminated&) {
            return absl::Substitute(
                "strlen(reinterpret_cast<const char*>($0)) + 1", ret_host_var);
          },
          [&](const auto& b) {
            using T = std::decay_t<decltype(b)>;
            static_assert(IsOneOf<T, ir::bounds::ElemSizedByOutparam,
                                  ir::bounds::ByteSizedByOutparam,
                                  ir::bounds::SizedByBinding>,
                          "Unhandled callback return bounds in "
                          "GetCallbackReturnSizeAsBytesExpr!");
            return absl::Substitute("sizeof(*$0)", ret_host_var);
          },
      },
      ret_buf->bounds);
}

// Emits parameter marshaling blocks (pre-call and post-call) for a host-side
// callback wrapper lambda given the callback's parameter list.
void EmitCallbackParamMarshaling(absl::Span<const ir::Parameter> parameters,
                                 std::vector<std::string>& lambda_params,
                                 std::vector<std::string>& lambda_call_args,
                                 std::vector<std::string>& pre_call_blocks,
                                 std::string& param_sync_post_call) {
  lambda_params.reserve(parameters.size());
  lambda_call_args.reserve(parameters.size());
  pre_call_blocks.reserve(parameters.size());

  for (const auto& p : parameters) {
    std::string p_name = p.name;
    std::string p_type = p.type.canonical_name;
    lambda_params.push_back(absl::Substitute("$0 $1", p_type, p_name));

    std::visit(
        absl::Overload{
            [&](const ir::BufferParam& p_buf) {
              lambda_call_args.push_back(absl::StrCat("sapi_host_", p_name));
              if (UsesCStringEmission(p_buf)) {
                pre_call_blocks.push_back(absl::Substitute(
                    R"(      std::optional<std::string> sapi_str_$0;
      $1 sapi_host_$0 = nullptr;
      if ($0 != nullptr) {
        auto sapi_cstr_status = sandbox->GetCString(
            sapi::v::RemotePtr(const_cast<char*>(
                reinterpret_cast<const char*>($0))));
        sandbox->Check(sapi_cstr_status.status());
        sapi_str_$0 = std::move(*sapi_cstr_status);
        sapi_host_$0 = sapi_str_$0->c_str();
      })",
                    p_name, p_type));
                return;
              }
              std::string size_expr;
              if (const auto* byte =
                      std::get_if<ir::bounds::ByteCount>(&p_buf.bounds)) {
                size_expr = byte->size_expr;
              } else if (const auto* elem = std::get_if<ir::bounds::ElemCount>(
                             &p_buf.bounds)) {
                size_expr = absl::Substitute(
                    "sandbox->CheckedMultiply(sizeof(*$0), ($1))", p_name,
                    elem->size_expr);
              } else {
                size_expr = absl::Substitute("sizeof(*$0)", p_name);
              }
              std::string maybe_transfer_from =
                  p_buf.direction == PointerDir::kOut
                      ? ""
                      : absl::Substitute(
                            "        "
                            "sandbox->Check(sandbox->"
                            "TransferFromSandboxee(&sapi_arr_$0."
                            "value()));\n",
                            p_name);
              pre_call_blocks.push_back(absl::Substitute(
                  R"(      $1 sapi_host_$0 = nullptr;
      std::optional<sapi::v::Array<char>> sapi_arr_$0;
      if ($0 != nullptr) {
        sapi_arr_$0.emplace($2);
        sapi_arr_$0->SetRemote(
            const_cast<void*>(reinterpret_cast<const void*>($0)));
$3        sapi_host_$0 = reinterpret_cast<$1>(sapi_arr_$0->GetData());
      })",
                  p_name, p_type, size_expr, maybe_transfer_from));
              if (p_buf.direction == PointerDir::kOut ||
                  p_buf.direction == PointerDir::kInOut) {
                absl::SubstituteAndAppend(
                    &param_sync_post_call,
                    R"(      if (sapi_arr_$0.has_value()) {
        sandbox->Check(sandbox->TransferToSandboxee(&sapi_arr_$0.value()));
      }
)",
                    p_name);
              }
            },
            [&](const ir::OpaquePointerParam& op) {
              lambda_call_args.push_back(absl::StrCat("sapi_host_", p_name));
              if (op.host_opaque_handle.has_value()) {
                if (const auto* alias =
                        std::get_if<ir::lifetime::AliasHostPtr>(&op.lifetime)) {
                  pre_call_blocks.push_back(absl::Substitute(
                      R"(      $1 sapi_expected_$0 =
          $2 == nullptr ? nullptr : reinterpret_cast<$1>($3);
      CHECK_EQ($0, sapi_expected_$0);
      $1 sapi_host_$0 = $2;)",
                      p_name, p_type, alias->host_param_name,
                      *op.host_opaque_handle));
                  return;
                }
              }
              pre_call_blocks.push_back(absl::Substitute(
                  R"(      $1 sapi_host_$0 = $0;)", p_name, p_type));
            },
            [&](const auto& inner) {
              using T = std::decay_t<decltype(inner)>;
              static_assert(
                  IsOneOf<T, ir::VoidParam, ir::ScalarParam, ir::CppStringParam,
                          ir::StructSyncParam, ir::CallbackParam>,
                  "Unhandled callback parameter payload in "
                  "EmitCallbackParamMarshaling!");
              if (p.direction().has_value()) {
                lambda_call_args.push_back(absl::StrCat("sapi_host_", p_name));
                std::string size_expr = absl::Substitute("sizeof(*$0)", p_name);
                std::string maybe_transfer_from =
                    p.direction() == PointerDir::kOut
                        ? ""
                        : absl::Substitute(
                              "        "
                              "sandbox->Check(sandbox->"
                              "TransferFromSandboxee(&sapi_arr_$0."
                              "value()));\n",
                              p_name);
                pre_call_blocks.push_back(absl::Substitute(
                    R"(      $1 sapi_host_$0 = nullptr;
      std::optional<sapi::v::Array<char>> sapi_arr_$0;
      if ($0 != nullptr) {
        sapi_arr_$0.emplace($2);
        sapi_arr_$0->SetRemote(
            const_cast<void*>(reinterpret_cast<const void*>($0)));
$3        sapi_host_$0 = reinterpret_cast<$1>(sapi_arr_$0->GetData());
      })",
                    p_name, p_type, size_expr, maybe_transfer_from));
                if (p.direction() == PointerDir::kOut ||
                    p.direction() == PointerDir::kInOut) {
                  absl::SubstituteAndAppend(
                      &param_sync_post_call,
                      R"(      if (sapi_arr_$0.has_value()) {
        sandbox->Check(sandbox->TransferToSandboxee(&sapi_arr_$0.value()));
      }
)",
                      p_name);
                }
              } else {
                lambda_call_args.push_back(p_name);
              }
            },
        },
        p.payload);
  }
}

// Emits host pre-call setup for callback arguments. Simple scalar callbacks are
// passed directly, while pointer/buffer callbacks are wrapped in a lambda
// trampoline that synchronizes parameters into host memory before invocation
// and transfers callback return values to sandbox memory.
std::string EmitCallbackHostPreCall(const ir::Parameter& cb_param,
                                    const ir::CallbackParam& cb) {
  if (!NeedsCallbackLambdaWrapper(cb)) {
    return absl::Substitute(
        R"(  std::optional<sapi::v::Callback> sapi_cb_$0;
  if ($0) {
    sapi_cb_$0.emplace($0);
    sandbox->Check(sandbox->Allocate(&sapi_cb_$0.value(),
                                     /*automatic_free=*/true));
  }
)",
        cb_param.name);
  }

  std::string ret_vars;
  std::string cb_ret_type = GetCallbackReturnType(cb);
  bool is_ret_ptr = CallbackReturnsPointer(cb);
  if (is_ret_ptr) {
    absl::SubstituteAndAppend(&ret_vars,
                              "  std::vector<std::unique_ptr<sapi::v::Var>> "
                              "sapi_cb_ret_vars_$0;\n",
                              cb_param.name);
    if (cb.is_callback_return_aliased) {
      absl::SubstituteAndAppend(&ret_vars,
                                "  absl::flat_hash_map<uintptr_t, void*> "
                                "sapi_alias_cb_return_map_$0;\n",
                                cb_param.name);
    }
  }

  std::vector<std::string> lambda_params;
  std::vector<std::string> lambda_call_args;
  std::vector<std::string> pre_call_blocks;
  std::string param_sync_post_call;
  EmitCallbackParamMarshaling(cb.callback_parameters, lambda_params,
                              lambda_call_args, pre_call_blocks,
                              param_sync_post_call);

  std::string param_sync_pre_call;
  if (!pre_call_blocks.empty()) {
    param_sync_pre_call =
        absl::StrCat(absl::StrJoin(pre_call_blocks, "\n\n"), "\n\n");
  }

  std::string lambda_call_str = absl::StrJoin(lambda_call_args, ", ");
  std::string lambda_body;

  if (is_ret_ptr) {
    std::string ret_size_expr = GetCallbackReturnSizeAsBytesExpr(cb_param, cb);
    std::string alias_map_code;
    if (cb.is_callback_return_aliased) {
      alias_map_code = absl::Substitute(
          "      "
          "sapi_alias_cb_return_map_$0[reinterpret_cast<uintptr_t>(\n"
          "          sapi_ret_var->GetRemote())] = "
          "sapi_$0_ret_host;\n",
          cb_param.name);
    }
    std::string transfer_code;
    bool ret_uninitialized =
        cb.uninitialized ||
        (cb.return_value && cb.return_value->uninitialized());
    if (!ret_uninitialized) {
      transfer_code =
          "      "
          "sandbox->Check(sandbox->TransferToSandboxee(sapi_ret_var."
          "get()));\n";
    }
    std::string maybe_post_call =
        param_sync_post_call.empty() ? ""
                                     : absl::StrCat(param_sync_post_call, "\n");
    lambda_body = absl::Substitute(
        R"($0      // Forward params -> args, and do the callback
      $1 sapi_$2_ret_host = $2($3);
$7      // If the callback returned null, no need to
      // allocate a sandbox copy, sync, etc.
      if (!sapi_$2_ret_host) {
        return nullptr;
      }
      // Otherwise, make a sandbox copy of the
      // return value, and return the sandbox copy.

      size_t ret_size_bytes = $4;
      auto sapi_ret_var = std::make_unique<sapi::v::Array<char>>(
          reinterpret_cast<char*>(sapi_$2_ret_host), ret_size_bytes);
      sandbox->Check(sandbox->Allocate(sapi_ret_var.get(),
                                       /*automatic_free=*/true));
$5$6      auto ret_remote_ptr = sapi_ret_var->GetRemote();
      sapi_cb_ret_vars_$2.push_back(std::move(sapi_ret_var));
      return reinterpret_cast<$1>(ret_remote_ptr);
)",
        param_sync_pre_call, cb_ret_type, cb_param.name, lambda_call_str,
        ret_size_expr, transfer_code, alias_map_code, maybe_post_call);
  } else if (cb_ret_type == "void") {
    if (param_sync_post_call.empty()) {
      lambda_body = absl::Substitute(
          R"($0      // Forward params -> args, and do the callback
      $1($2);
)",
          param_sync_pre_call, cb_param.name, lambda_call_str);
    } else {
      lambda_body = absl::Substitute(
          R"($0      // Forward params -> args, and do the callback
      $1($2);

$3)",
          param_sync_pre_call, cb_param.name, lambda_call_str,
          param_sync_post_call);
    }
  } else {
    if (param_sync_post_call.empty()) {
      lambda_body = absl::Substitute(
          R"($0      // Forward params -> args, and do the callback
      $1 sapi_$2_ret = $2($3);
      return sapi_$2_ret;
)",
          param_sync_pre_call, cb_ret_type, cb_param.name, lambda_call_str);
    } else {
      lambda_body = absl::Substitute(
          R"($0      // Forward params -> args, and do the callback
      $1 sapi_$2_ret = $2($3);

$4      return sapi_$2_ret;
)",
          param_sync_pre_call, cb_ret_type, cb_param.name, lambda_call_str,
          param_sync_post_call);
    }
  }

  std::string lambda_params_str = absl::StrJoin(lambda_params, ", ");

  return absl::Substitute(
      R"(  std::optional<sapi::v::Callback> sapi_cb_$0;
  // Variables to track callback return values, etc.
$1  // If the callback is not null, set the sapi_cb var to a lambda.
  if ($0) {
    auto sapi_lambda_$0 = [&]($2) -> $3 {
$4    };
    sapi_cb_$0.emplace(sapi_lambda_$0);
    sandbox->Check(sandbox->Allocate(&sapi_cb_$0.value(),
                                     /*automatic_free=*/true));
  }
)",
      cb_param.name, ret_vars, lambda_params_str, cb_ret_type, lambda_body);
}


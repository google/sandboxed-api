// Helper to retrieve the return type of a callback parameter.
std::string GetCallbackReturnType(const ir::CallbackParam& cb) {
  return cb.return_value != nullptr ? cb.return_value->type.canonical_name
                                    : "void";
}

// Returns true if the callback returns a pointer.
bool CallbackReturnsPointer(const ir::CallbackParam& cb) {
  return cb.return_value != nullptr && cb.return_value->type.is_pointer();
}

// Helper to extract canonical parameter types of a callback.
std::vector<std::string> GetCallbackParamTypes(const ir::CallbackParam& cb) {
  std::vector<std::string> types;
  types.reserve(cb.callback_parameters.size());
  for (const auto& param : cb.callback_parameters) {
    types.push_back(param.type.canonical_name);
  }
  return types;
}

// Emits the C++ parameter type declaration for the host wrapper.
std::string EmitHostParamDecl(const ir::Parameter& param) {
  return std::visit(
      absl::Overload{
          [&](const ir::CallbackParam& cb) {
            std::string ret_type = GetCallbackReturnType(cb);
            auto param_types = GetCallbackParamTypes(cb);
            if (cb.functor_template_name.has_value()) {
              return absl::Substitute(
                  "$0<$1($2)> $3", *cb.functor_template_name, ret_type,
                  absl::StrJoin(param_types, ", "), param.name);
            }
            return absl::Substitute("$0 (*$1)($2)", ret_type, param.name,
                                    absl::StrJoin(param_types, ", "));
          },
          [&](const auto& p) {
            using T = std::decay_t<decltype(p)>;
            static_assert(
                IsOneOf<T, ir::VoidParam, ir::ScalarParam, ir::BufferParam,
                        ir::CppStringParam, ir::OpaquePointerParam,
                        ir::StructSyncParam>,
                "Unhandled parameter payload type in EmitHostParamDecl!");
            return absl::Substitute("$0 $1", param.type.canonical_name,
                                    param.name);
          },
      },
      param.payload);
}

// Emits the C++ parameter type declaration for the sandboxee RPC wrapper.
// For strings and string references, LenValStruct pointers or data/size pairs
// are used.
std::string EmitSandboxeeParamDecl(const ir::Parameter& param) {
  return std::visit(
      absl::Overload{
          [&](const ir::CallbackParam& cb) {
            return absl::Substitute(
                "$0 (*$1)($2)", GetCallbackReturnType(cb), param.name,
                absl::StrJoin(GetCallbackParamTypes(cb), ", "));
          },
          [&](const ir::CppStringParam& str) {
            if (str.form == ir::CppStringParam::Form::kView ||
                str.form == ir::CppStringParam::Form::kValue ||
                (str.form == ir::CppStringParam::Form::kReference &&
                 str.is_const)) {
              return absl::Substitute("const char* $0_data, size_t $0_size",
                                      param.name);
            }
            return absl::Substitute("sapi::LenValStruct* $0", param.name);
          },
          [&](const auto& p) {
            using T = std::decay_t<decltype(p)>;
            static_assert(
                IsOneOf<T, ir::VoidParam, ir::ScalarParam, ir::BufferParam,
                        ir::OpaquePointerParam, ir::StructSyncParam>,
                "Unhandled parameter payload type in EmitSandboxeeParamDecl!");
            return absl::Substitute("$0 $1", param.type.canonical_name,
                                    param.name);
          },
      },
      param.payload);
}


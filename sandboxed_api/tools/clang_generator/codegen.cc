absl::StatusOr<std::string> FinalizeCode(
    absl::string_view body, bool is_header, bool add_includes,
    const absl::flat_hash_set<std::string>& includes) {
  std::string out;
  if (is_header) {
    out.append(kHeaderHeader);
  }
  out.append(kCommonHeader);
  if (add_includes) {
    std::vector<std::string> sorted_includes(includes.begin(), includes.end());
    std::sort(sorted_includes.begin(), sorted_includes.end());
    for (const auto& inc : sorted_includes) {
      absl::StrAppendFormat(&out, "#include %s\n", inc);
    }
  }
  absl::StrAppend(&out, "\n", body, kCommonFooter);
  return ReformatGoogleStyle("input", out);
}


std::optional<std::string> ExtractSoleDerefIdent(absl::string_view expr) {
  absl::string_view trimmed = absl::StripAsciiWhitespace(expr);
  if (!absl::ConsumePrefix(&trimmed, "*")) {
    return std::nullopt;
  }
  trimmed = absl::StripAsciiWhitespace(trimmed);
  absl::string_view rest = trimmed;
  if (ConsumeIdentifier(rest) && rest.empty()) {
    return std::string(trimmed);
  }
  return std::nullopt;
}

// Emits code to copy a callee-allocated buffer or null-terminated array from
// `remote_ptr_expr` in the sandboxee into a freshly `calloc`-allocated host
// buffer, immediately free the sandboxee allocation via `rpc_channel()->Free`,
// and assign the host pointer to `host_lhs`.
std::string EmitMallocCopyAndFreeFromSandbox(
    absl::string_view remote_ptr_expr, absl::string_view ptr_type,
    absl::string_view host_lhs, const ir::BufferBounds& buffer_bounds,
    bool uninitialized, absl::string_view indent) {
  std::string size_and_copy;
  if (std::holds_alternative<ir::bounds::NullTerminated>(buffer_bounds)) {
    size_and_copy = absl::Substitute(
        "$0    uintptr_t sapi_sb_ptr = "
        "reinterpret_cast<uintptr_t>(sapi_returned_sb_ptr);\n"
        "$0    std::vector<char> sapi_remote_arr =\n"
        "$0        sapi::lwbox::ReadNullTerminatedArray<\n"
        "$0            "
        "std::remove_pointer_t<decltype(sapi_returned_sb_ptr)>>(\n"
        "$0            *sandbox, sapi_sb_ptr);\n"
        "$0    sapi_host_copy = calloc(std::max<size_t>(sapi_remote_arr.size(),"
        " 1), sizeof(char));\n"
        "$0    CHECK_NE(sapi_host_copy, nullptr);\n"
        "$0    memcpy(sapi_host_copy, sapi_remote_arr.data(), "
        "sapi_remote_arr.size());\n",
        indent);
  } else {
    std::string size_expr = std::visit(
        absl::Overload{
            [&](const ir::bounds::ByteCount& byte) {
              if (std::optional<std::string> ptr_name =
                      ExtractSoleDerefIdent(byte.size_expr)) {
                return absl::Substitute(
                    "($0 == nullptr ? 0 : sapi::lwbox::CheckedToSizeT(*$0))",
                    *ptr_name);
              }
              return CompileCheckedSizeExpr(byte.size_expr);
            },
            [&](const ir::bounds::ElemCount& elem) {
              if (std::optional<std::string> ptr_name =
                      ExtractSoleDerefIdent(elem.size_expr)) {
                return absl::Substitute(
                    "($0 == nullptr ? 0 : "
                    "sandbox->CheckedMultiply(sizeof(*sapi_returned_sb_ptr), "
                    "sapi::lwbox::CheckedToSizeT(*$0)))",
                    *ptr_name);
              }
              return absl::Substitute(
                  "sandbox->CheckedMultiply(sizeof(*sapi_returned_sb_ptr), "
                  "($0))",
                  CompileCheckedSizeExpr(elem.size_expr));
            },
            [](const ir::bounds::SizedByBinding& binding) {
              std::string context_var =
                  ResolveContextName(binding.context_expr);
              std::string size_expr =
                  CompileSizedByBindingExpr(context_var, binding.binding_name);
              if (binding.is_elem_sized) {
                return absl::Substitute(
                    "sandbox->CheckedMultiply(sizeof(*sapi_returned_sb_ptr), "
                    "($0))",
                    size_expr);
              }
              return size_expr;
            },
            [](const ir::bounds::ByteSizedByOutparam& byte_out) {
              return absl::Substitute(
                  "($0 == nullptr ? 0 : sapi::lwbox::CheckedToSizeT(*$0))",
                  byte_out.outparam_name);
            },
            [](const ir::bounds::ElemSizedByOutparam& elem_out) {
              return absl::Substitute(
                  "($0 == nullptr ? 0 : "
                  "sandbox->CheckedMultiply(sizeof(*sapi_returned_sb_ptr), "
                  "sapi::lwbox::CheckedToSizeT(*$0)))",
                  elem_out.outparam_name);
            },
            [](const auto& b) {
              using T = std::decay_t<decltype(b)>;
              static_assert(
                  IsOneOf<T, ir::bounds::Singleton, ir::bounds::NullTerminated>,
                  "Unhandled buffer bounds in "
                  "EmitMallocCopyAndFreeFromSandbox!");
              return std::string("sizeof(*sapi_returned_sb_ptr)");
            },
        },
        buffer_bounds);
    if (uninitialized) {
      size_and_copy = absl::Substitute(
          "$0    size_t sapi_malloc_size = $1;\n"
          "$0    sapi_host_copy = calloc(std::max<size_t>(sapi_malloc_size, "
          "1), sizeof(char));\n"
          "$0    CHECK_NE(sapi_host_copy, nullptr);\n",
          indent, size_expr);
    } else {
      size_and_copy = absl::Substitute(
          "$0    uintptr_t sapi_sb_ptr = "
          "reinterpret_cast<uintptr_t>(sapi_returned_sb_ptr);\n"
          "$0    size_t sapi_malloc_size = $1;\n"
          "$0    sapi_host_copy = calloc(std::max<size_t>(sapi_malloc_size, "
          "1), sizeof(char));\n"
          "$0    CHECK_NE(sapi_host_copy, nullptr);\n"
          "$0    sapi::lwbox::SyncFromSandboxToHost(\n"
          "$0        *sandbox, sapi_sb_ptr, sapi_host_copy, "
          "sapi_malloc_size);\n",
          indent, size_expr);
    }
  }
  return absl::Substitute(
      "$0{\n"
      "$0  auto* sapi_returned_sb_ptr = $1;\n"
      "$0  void* sapi_host_copy = nullptr;\n"
      "$0  if (sapi_returned_sb_ptr != nullptr) {\n"
      "$2"
      "$0    sandbox->Check(sandbox->rpc_channel()->Free(\n"
      "$0        const_cast<void*>(reinterpret_cast<const void*>("
      "sapi_returned_sb_ptr))));\n"
      "$0  }\n"
      "$0  $3 = reinterpret_cast<$4>(sapi_host_copy);\n"
      "$0}\n",
      indent, remote_ptr_expr, size_and_copy, host_lhs, ptr_type);
}

// Strips the leading "<param_name>->" prefix from a struct member sync access
// path, returning the relative field path (e.g. "bar" or "inner.bar").
std::string RelativeStructMemberPath(absl::string_view param_name,
                                     const ir::StructMemberSync& sync) {
  if (sync.member_name.empty()) {
    return sync.access_path();
  }
  std::string top_arrow = absl::StrCat(param_name, "->");
  absl::string_view nested_prefix = sync.parent_prefix;
  absl::ConsumePrefix(&nested_prefix, top_arrow);
  return absl::StrCat(nested_prefix, sync.member_name);
}

// Converts a relative struct member path into a collision-free C++ identifier
// suffix. Single-level member names (without '.') pass through unchanged;
// nested paths escape '_' as "__" and '.' as "_d_" so "a.b" ("a_d_b") cannot
// collide with sibling "a_b" ("a__b").
std::string SanitizeIdentifierSuffix(absl::string_view s) {
  if (!absl::StrContains(s, '.')) {
    return std::string(s);
  }
  std::string out;
  out.reserve(s.size() + 4);
  for (char c : s) {
    if (c == '_') {
      out.append("__");
    } else if (c == '.') {
      out.append("_d_");
    } else {
      out.push_back(c);
    }
  }
  return out;
}

// Emits pre-call memory allocation and data synchronization for struct pointer
// members annotated with SANDBOX_STRUCT_SYNC.
std::string EmitStructMemberSyncsPreCall(
    const ir::Parameter& param, const ir::StructSyncParam& sync_param) {
  const bool struct_written_back =
      param.direction() != PointerDir::kIn && !param.type.is_const &&
      !(param.type.pointee && param.type.pointee->is_const);
  std::string ret;
  for (const auto& sync : sync_param.members) {
    std::string member_rel = RelativeStructMemberPath(param.name, sync);
    if (std::holds_alternative<ir::lifetime::Malloc>(sync.lifetime)) {
      absl::SubstituteAndAppend(
          &ret,
          "  if ($0 != nullptr) {\n"
          "    sapi_tmp_$0.mutable_data()->$1 = nullptr;\n"
          "  }\n",
          param.name, member_rel);
      continue;
    }
    std::string suffix =
        absl::StrCat(param.name, "_", SanitizeIdentifierSuffix(member_rel));
    std::string host_ptr_expr = sync.access_path();
    std::string ctx_decl;

    std::string size_calc = std::visit(
        absl::Overload{
            [&](const ir::bounds::NullTerminated&) {
              return absl::Substitute(
                  "sapi_member_size_$0 = "
                  "sapi::lwbox::NullTerminatedByteSize($1);\n",
                  suffix, host_ptr_expr);
            },
            [&](const ir::bounds::SizedByBinding& binding) {
              std::string context_var =
                  ResolveContextName(binding.context_expr);
              std::string ctx_init;
              if (struct_written_back) {
                // Pin the pre-call context key so a post-call struct writeback
                // that zeroes or alters sibling handle fields cannot redirect
                // or crash the post-call binding lookup.
                ctx_decl = absl::Substitute(
                    "  const void* sapi_member_ctx_$0 = nullptr;\n", suffix);
                ctx_init = absl::Substitute("sapi_member_ctx_$0 = $1;\n    ",
                                            suffix, context_var);
                context_var = absl::StrCat("sapi_member_ctx_", suffix);
              }
              std::string size_expr =
                  CompileSizedByBindingExpr(context_var, binding.binding_name);
              if (binding.is_elem_sized) {
                size_expr = absl::Substitute(
                    "sandbox->CheckedMultiply(sizeof(*($0)), ($1))",
                    host_ptr_expr, size_expr);
              }
              return absl::Substitute("$0sapi_member_size_$1 = $2;\n", ctx_init,
                                      suffix, size_expr);
            },
            [&](const ir::bounds::ByteCount& byte) {
              return absl::Substitute("sapi_member_size_$0 = $1;\n", suffix,
                                      CompileCheckedSizeExpr(byte.size_expr));
            },
            [&](const ir::bounds::ElemCount& elem) {
              return absl::Substitute(
                  "sapi_member_size_$0 = "
                  "sandbox->CheckedMultiply(sizeof(*($1)), ($2));\n",
                  suffix, host_ptr_expr,
                  CompileCheckedSizeExpr(elem.size_expr));
            },
            [&](const auto& b) {
              using T = std::decay_t<decltype(b)>;
              static_assert(IsOneOf<T, ir::bounds::Singleton,
                                    ir::bounds::ElemSizedByOutparam,
                                    ir::bounds::ByteSizedByOutparam>,
                            "Unhandled struct member bounds in "
                            "EmitStructMemberSyncsPreCall!");
              return absl::Substitute("sapi_member_size_$0 = sizeof(*($1));\n",
                                      suffix, host_ptr_expr);
            },
        },
        sync.bounds);

    std::string copy_code;
    if (sync.direction == PointerDir::kIn ||
        sync.direction == PointerDir::kInOut) {
      copy_code = absl::Substitute(
          R"(sandbox->Check(
     sandbox->rpc_channel()
         ->CopyToSandbox(
             reinterpret_cast<uintptr_t>(sapi_sb_copy_$0),
             absl::MakeSpan(reinterpret_cast<const char*>($1),
                            sapi_member_size_$0))
         .status());
)",
          suffix, host_ptr_expr);
    }

    std::string update_host_to_sb_ptr_code = absl::Substitute(
        R"(sapi_tmp_$0.mutable_data()->$1 =
   reinterpret_cast<decltype(sapi_tmp_$0.mutable_data()->$1)>(
       sapi_sb_copy_$2);
)",
        param.name, member_rel, suffix);

    absl::SubstituteAndAppend(&ret,
                              R"(  void* sapi_sb_copy_$0 = nullptr;
  size_t sapi_member_size_$0 = 0;
$6  if ($1 != nullptr && $2 != nullptr) {
    // Compute size
    $3
    // Allocate
    sandbox->Check(sandbox->rpc_channel()->Allocate(
        sapi_member_size_$0, &sapi_sb_copy_$0));
    // copy host to sb if needed
    $4
    // update ptr member (host to sb)
    $5
  }
)",
                              suffix, param.name, host_ptr_expr, size_calc,
                              copy_code, update_host_to_sb_ptr_code, ctx_decl);
  }
  if (param.direction() != PointerDir::kOut) {
    for (const auto& cb_field : sync_param.callbacks) {
      absl::SubstituteAndAppend(&ret,
                                R"(  if ($0 != nullptr) {
    sapi_tmp_$0.mutable_data()->$1 =
        reinterpret_cast<decltype(sapi_tmp_$0.mutable_data()->$1)>(
            $2(reinterpret_cast<uintptr_t>($0->$1)));
  }
)",
                                param.name, cb_field.member_name,
                                RegisterCallbackName(cb_field.typedef_name));
    }
  } else if (std::any_of(sync_param.members.begin(), sync_param.members.end(),
                         [](const ir::StructMemberSync& s) {
                           return s.direction != PointerDir::kSandboxOpaque;
                         })) {
    for (const auto& cb_field : sync_param.callbacks) {
      absl::SubstituteAndAppend(&ret,
                                R"(  if ($0 != nullptr) {
    sapi_tmp_$0.mutable_data()->$1 = nullptr;
  }
)",
                                param.name, cb_field.member_name);
    }
  }
  return ret;
}

// Emits post-call data synchronization from sandbox to host for struct pointer
// members, and either retains the remote pointer in ContextBindingRegistry or
// frees the temporary sandbox allocation.
std::string EmitStructMemberSyncsPostCall(
    const ir::Parameter& param, const ir::StructSyncParam& sync_param) {
  std::string out;
  for (const auto& sync : sync_param.members) {
    std::string member_rel = RelativeStructMemberPath(param.name, sync);
    std::string suffix =
        absl::StrCat(param.name, "_", SanitizeIdentifierSuffix(member_rel));
    std::string host_ptr_expr = sync.access_path();

    if (std::holds_alternative<ir::lifetime::Malloc>(sync.lifetime)) {
      std::string remote_expr =
          absl::Substitute("sapi_tmp_$0.data().$1", param.name, member_rel);
      std::string ptr_type = absl::Substitute("decltype($0)", host_ptr_expr);
      absl::SubstituteAndAppend(
          &out,
          "  if ($0 != nullptr) {\n"
          "$1"
          "  }\n",
          param.name,
          EmitMallocCopyAndFreeFromSandbox(remote_expr, ptr_type, host_ptr_expr,
                                           sync.bounds,
                                           /*uninitialized=*/false, "    "));
      continue;
    }

    std::string post_size_check;
    std::string copy_size_expr = absl::StrCat("sapi_member_size_", suffix);
    const bool struct_written_back =
        param.direction() != PointerDir::kIn && !param.type.is_const &&
        !(param.type.pointee && param.type.pointee->is_const);
    if (struct_written_back) {
      if (const auto* byte = std::get_if<ir::bounds::ByteCount>(&sync.bounds)) {
        post_size_check = absl::Substitute(
            "    size_t sapi_post_member_size_$0 =\n"
            "        $1;\n"
            "    if (sapi_post_member_size_$0 > sapi_member_size_$0) {\n"
            "      sandbox->Check(absl::OutOfRangeError(\n"
            "          absl::StrCat(\"Sandboxee returned size (\",\n"
            "                       sapi_post_member_size_$0,\n"
            "                       \") exceeding capacity (\",\n"
            "                       sapi_member_size_$0,\n"
            "                       \") for struct member $2\")));\n"
            "    }\n",
            suffix, CompileCheckedSizeExpr(byte->size_expr), host_ptr_expr);
        copy_size_expr = absl::StrCat("sapi_post_member_size_", suffix);
      } else if (const auto* elem =
                     std::get_if<ir::bounds::ElemCount>(&sync.bounds)) {
        post_size_check = absl::Substitute(
            "    size_t sapi_post_member_size_$0 =\n"
            "        sandbox->CheckedMultiply(\n"
            "            sizeof(*($1)), ($2));\n"
            "    if (sapi_post_member_size_$0 > sapi_member_size_$0) {\n"
            "      sandbox->Check(absl::OutOfRangeError(\n"
            "          absl::StrCat(\"Sandboxee returned size (\",\n"
            "                       sapi_post_member_size_$0,\n"
            "                       \") exceeding capacity (\",\n"
            "                       sapi_member_size_$0,\n"
            "                       \") for struct member $1\")));\n"
            "    }\n",
            suffix, host_ptr_expr, CompileCheckedSizeExpr(elem->size_expr));
        copy_size_expr = absl::StrCat("sapi_post_member_size_", suffix);
      } else if (const auto* binding =
                     std::get_if<ir::bounds::SizedByBinding>(&sync.bounds)) {
        std::string size_expr = CompileSizedByBindingExpr(
            absl::StrCat("sapi_member_ctx_", suffix), binding->binding_name);
        if (binding->is_elem_sized) {
          size_expr =
              absl::Substitute("sandbox->CheckedMultiply(sizeof(*($0)), ($1))",
                               host_ptr_expr, size_expr);
        }
        post_size_check = absl::Substitute(
            "    size_t sapi_post_member_size_$0 =\n"
            "        $1;\n"
            "    if (sapi_post_member_size_$0 > sapi_member_size_$0) {\n"
            "      sandbox->Check(absl::OutOfRangeError(\n"
            "          absl::StrCat(\"Sandboxee returned size (\",\n"
            "                       sapi_post_member_size_$0,\n"
            "                       \") exceeding capacity (\",\n"
            "                       sapi_member_size_$0,\n"
            "                       \") for struct member $2\")));\n"
            "    }\n",
            suffix, size_expr, host_ptr_expr);
        copy_size_expr = absl::StrCat("sapi_post_member_size_", suffix);
      }
    }
    if (sync.direction == PointerDir::kOut ||
        sync.direction == PointerDir::kInOut) {
      std::string rezero_sentinel;
      if (sync.direction == PointerDir::kInOut &&
          std::holds_alternative<ir::bounds::NullTerminated>(sync.bounds)) {
        rezero_sentinel = absl::Substitute(
            "    if ($1 != nullptr && sapi_member_size_$0 >= sizeof(*($1))) {\n"
            "      memset(reinterpret_cast<char*>($1) + sapi_member_size_$0 - "
            "sizeof(*($1)),\n"
            "             0, sizeof(*($1)));\n"
            "    }\n",
            suffix, host_ptr_expr);
      }
      absl::SubstituteAndAppend(&out,
                                R"(  if (sapi_sb_copy_$0 != nullptr) {
$4    sapi::lwbox::SyncFromSandboxToHost(
        *sandbox, reinterpret_cast<uintptr_t>(sapi_sb_copy_$0),
        reinterpret_cast<void*>($1), $3);
$2  }
)",
                                suffix, host_ptr_expr, rezero_sentinel,
                                copy_size_expr, post_size_check);
    } else if (!post_size_check.empty()) {
      absl::SubstituteAndAppend(&out,
                                R"(  if (sapi_sb_copy_$0 != nullptr) {
$1  }
)",
                                suffix, post_size_check);
    }
    if (sync.context_bound.retain_and_bind.has_value()) {
      std::string ctx_name =
          ResolveContextName(sync.context_bound.retain_and_bind->context);
      absl::SubstituteAndAppend(
          &out,
          R"(  if (sapi_sb_copy_$0 != nullptr && $1 != nullptr) {
    sapi::lwbox::ContextBindingRegistry::Instance()->RetainPointer(
        $1, "$2", reinterpret_cast<uintptr_t>(sapi_sb_copy_$0),
        sapi_member_size_$0);
  }
)",
          suffix, ctx_name, sync.context_bound.retain_and_bind->binding_name);
    } else {
      absl::SubstituteAndAppend(&out,
                                R"(  if (sapi_sb_copy_$0 != nullptr) {
    sandbox->Check(sandbox->rpc_channel()->Free(sapi_sb_copy_$0));
  }
)",
                                suffix);
    }
  }
  return out;
}

// Emits code to synchronize a returned or out-parameter pointer from the
// sandboxee, allocating a host buffer and caching/binding it in the
// ContextBindingRegistry. If already bound, synchronizes the existing host copy
// or re-binds if the remote sandbox pointer changed.
std::string EmitCopyFromAndBindOutPtrCode(
    const CopyFromAndBindOutPtr& cb, absl::string_view out_ptr_name,
    absl::string_view out_ptr_type, const ir::BufferBounds& buffer_bounds) {
  std::string ctx_name = ResolveContextName(cb.context);
  std::string size_calc;
  std::string alloc_and_copy_code;

  if (const auto* byte = std::get_if<ir::bounds::ByteCount>(&buffer_bounds)) {
    size_calc = absl::Substitute("size_t sapi_binding_size = $0;\n",
                                 CompileDerefOrRawSizeExpr(byte->size_expr));
    alloc_and_copy_code = R"(
        sapi_host_copy = calloc(sapi_binding_size, sizeof(char));
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, sapi_sb_ptr, sapi_host_copy, sapi_binding_size);
)";
  } else if (const auto* elem =
                 std::get_if<ir::bounds::ElemCount>(&buffer_bounds)) {
    size_calc = absl::Substitute(
        "size_t sapi_binding_size = "
        "sandbox->CheckedMultiply(sizeof(*sapi_returned_sb_ptr), ($0));\n",
        CompileDerefOrRawSizeExpr(elem->size_expr));
    alloc_and_copy_code = R"(
        sapi_host_copy = calloc(sapi_binding_size, sizeof(char));
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, sapi_sb_ptr, sapi_host_copy, sapi_binding_size);
)";
  } else if (std::holds_alternative<ir::bounds::NullTerminated>(
                 buffer_bounds)) {
    alloc_and_copy_code = R"(
        std::vector<char> sapi_remote_arr =
            sapi::lwbox::ReadNullTerminatedArray(
                *sandbox, sapi_sb_ptr, sizeof(*sapi_returned_sb_ptr));
        size_t sapi_binding_size =
            sapi_remote_arr.size() - sizeof(*sapi_returned_sb_ptr);
        sapi_host_copy = calloc(sapi_remote_arr.size(), sizeof(char));
        memcpy(sapi_host_copy, sapi_remote_arr.data(), sapi_binding_size);
)";
  } else if (const auto* binding =
                 std::get_if<ir::bounds::SizedByBinding>(&buffer_bounds)) {
    std::string context_var = ResolveContextName(binding->context_expr);
    std::string size_expr =
        CompileSizedByBindingExpr(context_var, binding->binding_name);
    if (binding->is_elem_sized) {
      size_expr = absl::Substitute(
          "sandbox->CheckedMultiply(sizeof(*sapi_returned_sb_ptr), ($0))",
          size_expr);
    }
    size_calc = absl::Substitute("size_t sapi_binding_size = $0;\n", size_expr);
    alloc_and_copy_code = R"(
        sapi_host_copy = calloc(sapi_binding_size, sizeof(char));
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, sapi_sb_ptr, sapi_host_copy, sapi_binding_size);
)";
  }

  // The `else` branch below reuses the host buffer recorded when the binding
  // was first created, and syncs it using `sapi_bound_buf->bytes`, the size
  // captured at bind time. If the sandboxee has since grown the buffer, only
  // the original number of bytes is copied back and the host copy is stale.
  // TODO(b/491828958): Re-read the current size instead of reusing the size
  // captured at bind time.
  return absl::Substitute(
      R"(  {  // Get or create context binding.
    auto* sapi_returned_sb_ptr = $2.GetValue();
    if (sapi_returned_sb_ptr != nullptr && $0 != nullptr) {
      uintptr_t sapi_sb_ptr = reinterpret_cast<uintptr_t>(sapi_returned_sb_ptr);
      void* sapi_host_copy = nullptr;
      auto sapi_bound_buf =
          sapi::lwbox::ContextBindingRegistry::Instance()
              ->GetBoundHostBuffer($0, "$1");
      if (!sapi_bound_buf.has_value() ||
          sapi_bound_buf->remote_ptr != sapi_sb_ptr) {
        $3$4        sapi::lwbox::ContextBindingRegistry::Instance()
            ->BindHostBuffer($0, "$1", sapi_sb_ptr, sapi_host_copy,
                             sapi_binding_size);
      } else {
        sapi_host_copy = sapi_bound_buf->host_ptr;
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, sapi_sb_ptr, sapi_host_copy, sapi_bound_buf->bytes);
      }
      $2.SetValue(reinterpret_cast<$5>(sapi_host_copy));
    }
  }
)",
      ctx_name, cb.binding_name, out_ptr_name, size_calc, alloc_and_copy_code,
      out_ptr_type);
}


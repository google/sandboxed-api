// EmitSandboxeeSrc
// -----------------------------------------------------------------------------

absl::StatusOr<std::string> EmitSandboxeeSrc(
    const GeneratorOptions& options, const ir::Library& library,
    const absl::flat_hash_set<std::string>& includes) {
  std::string out;
  EmitLibraryHeaders(options, out);

  if (library.sandboxee_code) {
    absl::StrAppend(&out, *library.sandboxee_code, "\n\n");
  }

  std::vector<const ir::Function*> sorted_funcs = GetSortedFunctions(library);

  for (const auto* func : sorted_funcs) {
    EmitFuncDecl(out, *func);
    absl::StrAppend(&out, ";\n\n");
    if (func->sandboxee_thunk) {
      absl::StrAppend(&out, "// Start of thunk\n", "extern \"C\" ",
                      func->sandboxee_thunk->body, "\n// End of thunk\n\n");
    } else {
      EmitWrapperDecl(out, *func);
      absl::StrAppend(&out, " {\n");

      std::vector<std::string> call_args;
      call_args.reserve(func->parameters.size());
      std::string post_call_code;

      for (size_t i = 0; i < func->parameters.size(); ++i) {
        const auto& param = func->parameters[i];
        std::visit(
            absl::Overload{
                [&](const ir::CppStringParam& str) {
                  if (str.form == ir::CppStringParam::Form::kView) {
                    call_args.push_back(absl::Substitute(
                        "std::string_view($0_data, $0_size)", param.name));
                  } else if (str.form == ir::CppStringParam::Form::kValue ||
                             (str.form ==
                                  ir::CppStringParam::Form::kReference &&
                              str.is_const)) {
                    call_args.push_back(absl::Substitute(
                        "std::string($0_data, $0_size)", param.name));
                  } else if (str.form == ir::CppStringParam::Form::kReference) {
                    absl::StrAppend(
                        &out,
                        absl::Substitute(
                            "  std::string "
                            "sapi_tmp_$0(reinterpret_cast<char*>($0->data), "
                            "$0->size);\n"
                            "  free($0->data);\n\n",
                            param.name));
                    call_args.push_back(absl::StrCat("sapi_tmp_", param.name));
                    absl::SubstituteAndAppend(
                        &post_call_code,
                        "  $0->size = sapi_tmp_$0.size();\n"
                        "  $0->data = "
                        "reinterpret_cast<uint8_t*>(malloc($0->size));\n"
                        "  if ($0->size > 0) {\n"
                        "    memcpy($0->data, sapi_tmp_$0.data(), "
                        "$0->size);\n"
                        "  }\n",
                        param.name);
                  } else {
                    // kPointer
                    absl::StrAppend(
                        &out,
                        absl::Substitute(
                            "  std::string* sapi_tmp_ptr_$0 = nullptr;\n"
                            "  std::string sapi_tmp_$0;\n"
                            "  if ($0 != nullptr) {\n"
                            "    sapi_tmp_$0 = "
                            "std::string(reinterpret_cast<char*>($0->data), "
                            "$0->size);\n"
                            "    free($0->data);\n"
                            "    sapi_tmp_ptr_$0 = &sapi_tmp_$0;\n"
                            "  }\n",
                            param.name));
                    call_args.push_back(
                        absl::StrCat("sapi_tmp_ptr_", param.name));
                    if (str.direction == PointerDir::kOut ||
                        str.direction == PointerDir::kInOut) {
                      absl::SubstituteAndAppend(
                          &post_call_code,
                          "  if ($0 != nullptr) {\n"
                          "    $0->size = sapi_tmp_$0.size();\n"
                          "    $0->data = "
                          "reinterpret_cast<uint8_t*>(malloc($0->size));\n"
                          "    if ($0->size > 0) {\n"
                          "      memcpy($0->data, sapi_tmp_$0.data(), "
                          "$0->size);\n"
                          "    }\n"
                          "  }\n",
                          param.name);
                    }
                  }
                },
                [&](const auto& p) {
                  using T = std::decay_t<decltype(p)>;
                  static_assert(IsOneOf<T, ir::VoidParam, ir::ScalarParam,
                                        ir::BufferParam, ir::OpaquePointerParam,
                                        ir::StructSyncParam, ir::CallbackParam>,
                                "Unhandled parameter payload type in sandboxee "
                                "call arguments!");
                  call_args.push_back(param.name);
                },
            },
            param.payload);
      }

      std::string call_args_str = absl::StrJoin(call_args, ", ");
      std::string target_call =
          absl::Substitute("$0($1)", func->name, call_args_str);

      if (func->return_value) {
        if (func->return_value->type.kind == ir::TypeKind::kString) {
          absl::SubstituteAndAppend(
              &out,
              "  std::string sapi_ret_val = $0;\n"
              "  sapi_ret_arg->size = sapi_ret_val.size();\n"
              "  sapi_ret_arg->data = "
              "reinterpret_cast<uint8_t*>(malloc(sapi_ret_arg->size));\n"
              "  if (sapi_ret_arg->size > 0) {\n"
              "    memcpy(sapi_ret_arg->data, sapi_ret_val.data(), "
              "sapi_ret_arg->size);\n"
              "  }\n",
              target_call);
        } else {
          // Using auto avoids potential syntax errors with complex return
          // types (e.g., function pointers).
          absl::SubstituteAndAppend(&out,
                                    "  auto sapi_ret_val = $0;\n"
                                    "  *sapi_ret_arg = sapi_ret_val;\n",
                                    target_call);
        }
      } else {
        absl::StrAppend(&out, "  ", target_call, ";\n");
      }

      absl::StrAppend(&out, post_call_code);
      absl::StrAppend(&out, "}\n\n");
    }
  }

  absl::flat_hash_set<std::string> sandboxee_includes = includes;
  if (HasStringType(library)) {
    sandboxee_includes.insert(
        absl::Substitute("\"$0sandboxed_api/lenval_core.h\"", kIncludePrefix));
  }
  for (const auto* func : sorted_funcs) {
    if (func->return_value &&
        func->return_value->type.kind == ir::TypeKind::kString) {
      sandboxee_includes.insert("<string>");
    }
    for (const auto& param : func->parameters) {
      std::visit(
          absl::Overload{
              [&](const ir::CppStringParam& str) {
                if (str.form == ir::CppStringParam::Form::kView) {
                  sandboxee_includes.insert("<string_view>");
                } else if (str.form == ir::CppStringParam::Form::kPointer) {
                  sandboxee_includes.insert("<string>");
                  sandboxee_includes.insert("<memory>");
                } else {
                  sandboxee_includes.insert("<string>");
                }
              },
              [&](const auto& p) {
                using T = std::decay_t<decltype(p)>;
                static_assert(IsOneOf<T, ir::VoidParam, ir::ScalarParam,
                                      ir::BufferParam, ir::OpaquePointerParam,
                                      ir::StructSyncParam, ir::CallbackParam>,
                              "Unhandled parameter payload in EmitSandboxeeSrc "
                              "includes!");
              },
          },
          param.payload);
    }
  }

  return FinalizeCode(out, /*is_header=*/false, /*add_includes=*/true,
                      sandboxee_includes);
}

// -----------------------------------------------------------------------------
// EmitSandboxeeMain
// -----------------------------------------------------------------------------

absl::StatusOr<std::string> EmitSandboxeeMain(const GeneratorOptions& options,
                                              const ir::Library& library) {
  std::string out;
  std::vector<const ir::Function*> sorted_funcs = GetSortedFunctions(library);
  for (const auto* func : sorted_funcs) {
    absl::StrAppend(&out, "extern \"C\" void ", func->name, "();\n");
  }
  absl::StrAppend(&out, "\nint main() {\n");
  for (const auto* func : sorted_funcs) {
    absl::StrAppend(&out, "  ", func->name, "();\n");
  }
  absl::StrAppend(&out, "}\n");
  return FinalizeCode(out, /*is_header=*/false, /*add_includes=*/false, {});
}


// Returns true if the callback returns a pointer or if any of its parameters
// are pointers or annotated buffers. In these cases, we must wrap the callback
// in a host-side lambda trampoline to perform translation, syncing, or
// tracking.
bool NeedsCallbackLambdaWrapper(const ir::CallbackParam& cb) {
  if (CallbackReturnsPointer(cb)) {
    return true;
  }
  for (const auto& p : cb.callback_parameters) {
    bool needs_wrap = std::visit(
        absl::Overload{
            [](const ir::BufferParam&) { return true; },
            [&](const auto& inner) {
              using T = std::decay_t<decltype(inner)>;
              static_assert(
                  IsOneOf<T, ir::VoidParam, ir::ScalarParam, ir::CppStringParam,
                          ir::OpaquePointerParam, ir::StructSyncParam,
                          ir::CallbackParam, ir::SandboxeeCallbackParam>,
                  "Unhandled callback parameter payload in "
                  "NeedsCallbackLambdaWrapper!");
              return p.direction().has_value();
            },
        },
        p.payload);
    if (needs_wrap) return true;
  }
  return false;
}

// Computes the size in bytes for a callback return buffer.
std::string GetCallbackReturnSizeAsBytesExpr(const ir::Parameter& cb_param,
                                             const ir::CallbackParam& cb) {
  std::string ret_host_var = absl::StrCat("sapi_", cb_param.name, "_ret_host");
  const auto* ret_buf =
      cb.return_value ? cb.return_value->As<ir::BufferParam>() : nullptr;
  if (ret_buf == nullptr) {
    return absl::Substitute("sizeof(*$0)", ret_host_var);
  }
  return std::visit(
      absl::Overload{
          [&](const ir::bounds::Singleton&) {
            return absl::Substitute("sizeof(*$0)", ret_host_var);
          },
          [&](const ir::bounds::ElemCount& elem) {
            return absl::Substitute(
                "sandbox->CheckedMultiply(sizeof(*$0), ($1))", ret_host_var,
                CompileCheckedSizeExpr(elem.size_expr));
          },
          [](const ir::bounds::ByteCount& byte) {
            return CompileCheckedSizeExpr(byte.size_expr);
          },
          [&](const ir::bounds::NullTerminated&) {
            if (cb.return_value != nullptr &&
                IsConstCharPointee(cb.return_value->type)) {
              return absl::Substitute(
                  "strlen(reinterpret_cast<const char*>($0)) + 1",
                  ret_host_var);
            }
            return absl::Substitute("sapi::lwbox::NullTerminatedByteSize($0)",
                                    ret_host_var);
          },
          [&](const auto& b) {
            using T = std::decay_t<decltype(b)>;
            static_assert(IsOneOf<T, ir::bounds::ElemSizedByOutparam,
                                  ir::bounds::ByteSizedByOutparam,
                                  ir::bounds::SizedByBinding>,
                          "Unhandled callback return bounds in "
                          "GetCallbackReturnSizeAsBytesExpr!");
            return absl::Substitute("sizeof(*$0)", ret_host_var);
          },
      },
      ret_buf->bounds);
}

// Emits host-side pre-call marshaling for a multi-level pointer parameter
// passed from the sandboxee into a host callback (`p_buf.pointee != nullptr`).
//
// Security invariant (TOCTOU / double-fetch prevention):
// Both the outer pointer table (`sapi_outer_arr_<p>`) and every non-null inner
// element buffer (`sapi_elem_bufs_<p>`) are copied once into host-owned
// staging vectors before invoking the host callback, and the host callback
// receives `sapi_host_ptrs_<p>.data()` pointing exclusively into those host
// vectors. For `NullTerminated` outer pointer arrays, `NullTerminatedCount` is
// computed on the host-staged copy `sapi_outer_arr_<p>` rather than re-scanning
// sandboxee memory, so a concurrent thread in a compromised sandboxee cannot
// race to grow the pointer array past `sapi_host_ptrs_<p>` or swap pointer
// entries between length calculation and element copy.
void EmitMultiLevelCallbackParamMarshaling(
    const ir::Parameter& p, const ir::BufferParam& p_buf,
    std::vector<std::string>& pre_call_blocks) {
  std::string p_name = p.name;
  std::string p_type = p.type.canonical_name;
  std::string inner_ptr_type = p.type.pointee_value_type_name();
  const ir::Parameter& inner_param = *p_buf.pointee;

  std::string read_outer;
  if (std::holds_alternative<ir::bounds::NullTerminated>(p_buf.bounds)) {
    read_outer = absl::Substitute(
        R"(        std::vector<char> sapi_outer_arr_$0 =
            sapi::lwbox::ReadNullTerminatedArray(
                *sandbox, reinterpret_cast<uintptr_t>($0), sizeof($1));
        const auto* sapi_remote_ptrs_$0 =
            reinterpret_cast<$1 const*>(sapi_outer_arr_$0.data());
        size_t sapi_count_$0 =
            sapi::lwbox::NullTerminatedCount(sapi_remote_ptrs_$0);
        sapi_host_ptrs_$0.assign(sapi_count_$0 + 1, nullptr);)",
        p_name, inner_ptr_type);
  } else {
    std::string count_expr = std::visit(
        absl::Overload{
            [](const ir::bounds::Singleton&) -> std::string { return "1"; },
            [](const ir::bounds::ElemCount& e) -> std::string {
              return CompileCheckedSizeExpr(e.size_expr);
            },
            [&](const ir::bounds::ByteCount& b) -> std::string {
              return absl::Substitute("($0 / sizeof($1))",
                                      CompileCheckedSizeExpr(b.size_expr),
                                      inner_ptr_type);
            },
            [](const auto& b) -> std::string {
              using T = std::decay_t<decltype(b)>;
              static_assert(IsOneOf<T, ir::bounds::NullTerminated,
                                    ir::bounds::SizedByBinding,
                                    ir::bounds::ElemSizedByOutparam,
                                    ir::bounds::ByteSizedByOutparam>,
                            "Unhandled outer bounds in "
                            "EmitCallbackMultiLevelPointerParam!");
              return "1";
            },
        },
        p_buf.bounds);
    read_outer = absl::Substitute(
        R"(        size_t sapi_count_$0 = static_cast<size_t>($2);
        std::vector<char> sapi_outer_arr_$0(
            sandbox->CheckedMultiply(sizeof($1), sapi_count_$0));
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, reinterpret_cast<uintptr_t>($0),
            sapi_outer_arr_$0.data(), sapi_outer_arr_$0.size());
        const auto* sapi_remote_ptrs_$0 =
            reinterpret_cast<$1 const*>(sapi_outer_arr_$0.data());
        sapi_host_ptrs_$0.assign(std::max<size_t>(sapi_count_$0, 1), nullptr);)",
        p_name, inner_ptr_type, count_expr);
  }

  std::string elem_bufs_decl;
  std::string elem_marshal;
  if (inner_param.Is<ir::OpaquePointerParam>()) {
    elem_marshal = absl::Substitute(
        R"(          sapi_host_ptrs_$0[sapi_i] = sapi_remote_ptrs_$0[sapi_i];)",
        p_name);
  } else if (const auto* inner_buf = inner_param.As<ir::BufferParam>()) {
    CHECK(inner_buf->pointee == nullptr)
        << "Multi-level callback parameters deeper than 2 levels are not "
           "supported";
    elem_bufs_decl = absl::Substitute(
        "      std::vector<std::vector<char>> sapi_elem_bufs_$0;\n", p_name);
    if (std::holds_alternative<ir::bounds::NullTerminated>(inner_buf->bounds)) {
      if (inner_param.type.is_pointee_record()) {
        elem_marshal = absl::Substitute(
            R"(          if (sapi_remote_ptrs_$0[sapi_i] != nullptr) {
            sapi_elem_bufs_$0.push_back(
                sapi::lwbox::ReadNullTerminatedArray<$2>(
                    *sandbox,
                    reinterpret_cast<uintptr_t>(sapi_remote_ptrs_$0[sapi_i])));
            sapi_host_ptrs_$0[sapi_i] =
                reinterpret_cast<$1>(sapi_elem_bufs_$0.back().data());
          })",
            p_name, inner_ptr_type,
            inner_param.type.unqualified_pointee_type_name());
      } else {
        elem_marshal = absl::Substitute(
            R"(          if (sapi_remote_ptrs_$0[sapi_i] != nullptr) {
            sapi_elem_bufs_$0.push_back(
                sapi::lwbox::ReadNullTerminatedArray(
                    *sandbox,
                    reinterpret_cast<uintptr_t>(sapi_remote_ptrs_$0[sapi_i]),
                    sizeof(**$0)));
            sapi_host_ptrs_$0[sapi_i] =
                reinterpret_cast<$1>(sapi_elem_bufs_$0.back().data());
          })",
            p_name, inner_ptr_type);
      }
    } else {
      std::string elem_bytes_expr =
          std::visit(absl::Overload{
                         [&](const ir::bounds::Singleton&) -> std::string {
                           return absl::Substitute("sizeof(**$0)", p_name);
                         },
                         [&](const ir::bounds::ElemCount& e) -> std::string {
                           return absl::Substitute(
                               "sandbox->CheckedMultiply(sizeof(**$0), ($1))",
                               p_name, CompileCheckedSizeExpr(e.size_expr));
                         },
                         [](const ir::bounds::ByteCount& b) -> std::string {
                           return CompileCheckedSizeExpr(b.size_expr);
                         },
                         [&](const auto&) -> std::string {
                           return absl::Substitute("sizeof(**$0)", p_name);
                         },
                     },
                     inner_buf->bounds);
      elem_marshal = absl::Substitute(
          R"(          if (sapi_remote_ptrs_$0[sapi_i] != nullptr) {
            size_t sapi_elem_bytes = $2;
            sapi_elem_bufs_$0.emplace_back(
                std::max<size_t>(sapi_elem_bytes, 1));
            sapi::lwbox::SyncFromSandboxToHost(
                *sandbox,
                reinterpret_cast<uintptr_t>(sapi_remote_ptrs_$0[sapi_i]),
                sapi_elem_bufs_$0.back().data(), sapi_elem_bytes);
            sapi_host_ptrs_$0[sapi_i] =
                reinterpret_cast<$1>(sapi_elem_bufs_$0.back().data());
          })",
          p_name, inner_ptr_type, elem_bytes_expr);
    }
  }

  pre_call_blocks.push_back(absl::Substitute(
      R"($2      std::vector<$1> sapi_host_ptrs_$0;
      $3 sapi_host_$0 = nullptr;
      if ($0 != nullptr) {
$4
        for (size_t sapi_i = 0; sapi_i < sapi_count_$0; ++sapi_i) {
$5
        }
        sapi_host_$0 = reinterpret_cast<$3>(sapi_host_ptrs_$0.data());
      })",
      p_name, inner_ptr_type, elem_bufs_decl, p_type, read_outer,
      elem_marshal));
}

// Emits parameter marshaling blocks (pre-call and post-call) for a host-side
// callback wrapper lambda given the callback's parameter list.
//
// Security note (Host-Private Buffer Copies & TOCTOU Protection):
// Every pointer/buffer argument arriving from the sandboxee (`SANDBOX_IN_PTR`,
// `SANDBOX_OUT_PTR`, `SANDBOX_INOUT_PTR`) is copied into a freshly allocated
// host-owned buffer (`sapi::v::Array<char>`) before the user's host callback is
// invoked, and copied back out only after the callback returns. The raw
// sandboxee pointer is never passed to the host callback. This guarantees:
//   1. Under Sandbox2 (out-of-process), `TransferFromSandboxee` /
//      `TransferToSandboxee` target the sandboxee's PID rather than host
//      memory, so a forged host address in `req.args` cannot read or corrupt
//      host memory.
//   2. Under both Sandbox2 and future LFI (in-process sandboxing), the host
//      callback operates on a private host buffer that a concurrent thread
//      inside the sandboxee cannot race-modify (TOCTOU) during execution.
void EmitCallbackParamMarshaling(absl::Span<const ir::Parameter> parameters,
                                 std::vector<std::string>& lambda_params,
                                 std::vector<std::string>& lambda_call_args,
                                 std::vector<std::string>& pre_call_blocks,
                                 std::string& param_sync_post_call) {
  lambda_params.reserve(parameters.size());
  lambda_call_args.reserve(parameters.size());
  pre_call_blocks.reserve(parameters.size());

  for (const auto& p : parameters) {
    std::string p_name = p.name;
    std::string p_type = p.type.canonical_name;
    lambda_params.push_back(absl::Substitute("$0 $1", p_type, p_name));

    std::visit(
        absl::Overload{
            [&](const ir::BufferParam& p_buf) {
              lambda_call_args.push_back(absl::StrCat("sapi_host_", p_name));
              if (p_buf.pointee != nullptr) {
                EmitMultiLevelCallbackParamMarshaling(p, p_buf,
                                                      pre_call_blocks);
                return;
              }
              if (UsesCStringEmission(p, p_buf)) {
                pre_call_blocks.push_back(absl::Substitute(
                    R"(      std::optional<std::string> sapi_str_$0;
      $1 sapi_host_$0 = nullptr;
      if ($0 != nullptr) {
        auto sapi_cstr_status = sandbox->GetCString(
            sapi::v::RemotePtr(const_cast<char*>(
                reinterpret_cast<const char*>($0))));
        sandbox->Check(sapi_cstr_status.status());
        sapi_str_$0 = std::move(*sapi_cstr_status);
        sapi_host_$0 = sapi_str_$0->c_str();
      })",
                    p_name, p_type));
                return;
              }
              if (std::holds_alternative<ir::bounds::NullTerminated>(
                      p_buf.bounds)) {
                if (p.type.is_pointee_record()) {
                  pre_call_blocks.push_back(absl::Substitute(
                      R"(      std::vector<char> sapi_arr_$0;
      $1 sapi_host_$0 = nullptr;
      if ($0 != nullptr) {
        sapi_arr_$0 = sapi::lwbox::ReadNullTerminatedArray<$2>(
            *sandbox, reinterpret_cast<uintptr_t>($0));
        sapi_host_$0 = reinterpret_cast<$1>(sapi_arr_$0.data());
      })",
                      p_name, p_type, p.type.unqualified_pointee_type_name()));
                } else {
                  pre_call_blocks.push_back(absl::Substitute(
                      R"(      std::vector<char> sapi_arr_$0;
      $1 sapi_host_$0 = nullptr;
      if ($0 != nullptr) {
        sapi_arr_$0 = sapi::lwbox::ReadNullTerminatedArray(
            *sandbox, reinterpret_cast<uintptr_t>($0), sizeof(*$0));
        sapi_host_$0 = reinterpret_cast<$1>(sapi_arr_$0.data());
      })",
                      p_name, p_type));
                }
                return;
              }
              std::string size_expr = GetParamCapacityAsBytesExpr(p, p_buf);
              // Output-only callback buffers (including `SANDBOX_OUT_PTR` count
              // siblings) must never be transferred from the untrusted
              // sandboxee before invoking the host callback: an uninitialized
              // or sandboxee-crafted count would otherwise trigger `CHECK_LE`
              // or overwrite the output buffer on early callback return. Zero
              // the host buffer instead so unwritten output slots stay 0.
              std::string maybe_transfer_from =
                  p_buf.direction == PointerDir::kOut
                      ? absl::Substitute(
                            "        if (sapi_arr_$0->GetSize() > 0) {\n"
                            "          memset(sapi_arr_$0->GetData(), 0, "
                            "sapi_arr_$0->GetSize());\n"
                            "        }\n",
                            p_name)
                      : absl::Substitute(
                            "        "
                            "sandbox->Check(sandbox->"
                            "TransferFromSandboxee(&sapi_arr_$0."
                            "value()));\n",
                            p_name);
              pre_call_blocks.push_back(absl::Substitute(
                  R"(      $1 sapi_host_$0 = nullptr;
      std::optional<sapi::v::Array<char>> sapi_arr_$0;
      if ($0 != nullptr) {
        sapi_arr_$0.emplace($2);
        sapi_arr_$0->SetRemote(
            const_cast<void*>(reinterpret_cast<const void*>($0)));
$3        sapi_host_$0 = reinterpret_cast<$1>(sapi_arr_$0->GetData());
      })",
                  p_name, p_type, size_expr, maybe_transfer_from));
              if (p_buf.direction == PointerDir::kOut ||
                  p_buf.direction == PointerDir::kInOut) {
                std::visit(
                    absl::Overload{
                        [&](const ir::bounds::ElemSizedByOutparam& elem_out) {
                          std::string active_bytes_expr = absl::Substitute(
                              "(sapi_host_$1 == nullptr ? 0 : "
                              "sandbox->CheckedMultiply(sizeof(*$0), "
                              "sapi::lwbox::CheckedToSizeT(*sapi_host_$1)))",
                              p_name, elem_out.outparam_name);
                          absl::SubstituteAndAppend(
                              &param_sync_post_call,
                              R"(      if (sapi_arr_$0.has_value()) {
        size_t sapi_out_bytes_$0 = $1;
        CHECK_LE(sapi_out_bytes_$0, sapi_arr_$0->GetSize());
        if (sapi_out_bytes_$0 > 0) {
          sandbox->Check(
              sandbox->rpc_channel()
                  ->CopyToSandbox(
                      reinterpret_cast<uintptr_t>($0),
                      absl::MakeSpan(sapi_arr_$0->GetData(),
                                     sapi_out_bytes_$0))
                  .status());
        }
      }
)",
                              p_name, active_bytes_expr);
                        },
                        [&](const ir::bounds::ByteSizedByOutparam& byte_out) {
                          std::string active_bytes_expr = absl::Substitute(
                              "(sapi_host_$0 == nullptr ? 0 : "
                              "sapi::lwbox::CheckedToSizeT(*sapi_host_$0))",
                              byte_out.outparam_name);
                          absl::SubstituteAndAppend(
                              &param_sync_post_call,
                              R"(      if (sapi_arr_$0.has_value()) {
        size_t sapi_out_bytes_$0 = $1;
        CHECK_LE(sapi_out_bytes_$0, sapi_arr_$0->GetSize());
        if (sapi_out_bytes_$0 > 0) {
          sandbox->Check(
              sandbox->rpc_channel()
                  ->CopyToSandbox(
                      reinterpret_cast<uintptr_t>($0),
                      absl::MakeSpan(sapi_arr_$0->GetData(),
                                     sapi_out_bytes_$0))
                  .status());
        }
      }
)",
                              p_name, active_bytes_expr);
                        },
                        [&](const auto& b) {
                          using B = std::decay_t<decltype(b)>;
                          static_assert(IsOneOf<B, ir::bounds::Singleton,
                                                ir::bounds::ElemCount,
                                                ir::bounds::ByteCount,
                                                ir::bounds::SizedByBinding,
                                                ir::bounds::NullTerminated>,
                                        "Unhandled BufferBounds in "
                                        "EmitCallbackParamMarshaling!");
                          absl::SubstituteAndAppend(
                              &param_sync_post_call,
                              R"(      if (sapi_arr_$0.has_value()) {
        sandbox->Check(sandbox->TransferToSandboxee(&sapi_arr_$0.value()));
      }
)",
                              p_name);
                        },
                    },
                    p_buf.bounds);
              }
            },
            [&](const ir::OpaquePointerParam& op) {
              lambda_call_args.push_back(absl::StrCat("sapi_host_", p_name));
              if (op.host_opaque_handle.has_value()) {
                if (const auto* alias =
                        std::get_if<ir::lifetime::AliasHostPtr>(&op.lifetime)) {
                  pre_call_blocks.push_back(absl::Substitute(
                      R"(      $1 sapi_expected_$0 =
          $2 == nullptr ? nullptr : reinterpret_cast<$1>($3);
      CHECK_EQ($0, sapi_expected_$0);
      $1 sapi_host_$0 = $2;)",
                      p_name, p_type, alias->host_param_name,
                      *op.host_opaque_handle));
                  return;
                }
              }
              pre_call_blocks.push_back(absl::Substitute(
                  R"(      $1 sapi_host_$0 = $0;)", p_name, p_type));
            },
            [&](const ir::StructSyncParam& sync) {
              CHECK(sync.members.empty() && sync.callbacks.empty())
                  << "Deeply synced or callback-bearing StructSyncParam is not "
                     "supported in callbacks: "
                  << p_name;
              lambda_call_args.push_back(absl::StrCat("sapi_host_", p_name));
              std::string size_expr = absl::Substitute("sizeof(*$0)", p_name);
              std::string maybe_transfer_from =
                  sync.direction == PointerDir::kOut
                      ? ""
                      : absl::Substitute(
                            "        "
                            "sandbox->Check(sandbox->"
                            "TransferFromSandboxee(&sapi_arr_$0."
                            "value()));\n",
                            p_name);
              pre_call_blocks.push_back(absl::Substitute(
                  R"(      $1 sapi_host_$0 = nullptr;
      std::optional<sapi::v::Array<char>> sapi_arr_$0;
      if ($0 != nullptr) {
        sapi_arr_$0.emplace($2);
        sapi_arr_$0->SetRemote(
            const_cast<void*>(reinterpret_cast<const void*>($0)));
$3        sapi_host_$0 = reinterpret_cast<$1>(sapi_arr_$0->GetData());
      })",
                  p_name, p_type, size_expr, maybe_transfer_from));
              if (sync.direction == PointerDir::kOut ||
                  sync.direction == PointerDir::kInOut) {
                absl::SubstituteAndAppend(
                    &param_sync_post_call,
                    R"(      if (sapi_arr_$0.has_value()) {
        sandbox->Check(sandbox->TransferToSandboxee(&sapi_arr_$0.value()));
      }
)",
                    p_name);
              }
            },
            [&](const auto& inner) {
              using T = std::decay_t<decltype(inner)>;
              static_assert(
                  IsOneOf<T, ir::VoidParam, ir::ScalarParam, ir::CppStringParam,
                          ir::CallbackParam, ir::SandboxeeCallbackParam>,
                  "Unhandled callback parameter payload in "
                  "EmitCallbackParamMarshaling!");
              lambda_call_args.push_back(p_name);
            },
        },
        p.payload);
  }

  // When an `ElemSizedByOutparam` / `ByteSizedByOutparam` callback buffer
  // references a `SANDBOX_INOUT_PTR` count sibling, `*sapi_host_<outparam>` was
  // transferred from the untrusted sandboxee before the call. Validate that it
  // is non-negative and fits within `sapi_arr_<buf>->GetSize()` before invoking
  // the host callback so the callback cannot index out of bounds on the host
  // heap or leave an out-of-range count intact on early return.
  for (const auto& p : parameters) {
    const auto* p_buf = p.As<ir::BufferParam>();
    if (p_buf == nullptr) {
      continue;
    }
    absl::string_view outparam_name;
    std::string in_bytes_expr;
    if (const auto* elem_out =
            std::get_if<ir::bounds::ElemSizedByOutparam>(&p_buf->bounds)) {
      outparam_name = elem_out->outparam_name;
      in_bytes_expr = absl::Substitute(
          "sandbox->CheckedMultiply(sizeof(*$0), "
          "sapi::lwbox::CheckedToSizeT(*sapi_host_$1))",
          p.name, outparam_name);
    } else if (const auto* byte_out =
                   std::get_if<ir::bounds::ByteSizedByOutparam>(
                       &p_buf->bounds)) {
      outparam_name = byte_out->outparam_name;
      in_bytes_expr = absl::Substitute(
          "sapi::lwbox::CheckedToSizeT(*sapi_host_$0)", outparam_name);
    } else {
      continue;
    }
    const ir::Parameter* out_sib = nullptr;
    for (const auto& cand : parameters) {
      if (cand.name == outparam_name) {
        out_sib = &cand;
        break;
      }
    }
    if (out_sib != nullptr && out_sib->direction() == PointerDir::kInOut) {
      pre_call_blocks.push_back(absl::Substitute(
          R"(      if (sapi_host_$1 != nullptr) {
        size_t sapi_in_bytes_$0 =
            $2;
        if (sapi_arr_$0.has_value()) {
          CHECK_LE(sapi_in_bytes_$0, sapi_arr_$0->GetSize());
        }
      })",
          p.name, outparam_name, in_bytes_expr));
    }
  }
}

// Emits host pre-call setup for callback arguments. Plain C function pointers
// with a callback typedef register through `sapi_register_callback_<typedef>`
// so that a callback retained by the library survives the call that installed
// it and unwraps host thunks back to their native sandboxee addresses.
std::string EmitCallbackHostPreCall(const ir::Parameter& cb_param,
                                    const ir::CallbackParam& cb) {
  if (cb.typedef_name.has_value() && !cb.functor_template_name.has_value()) {
    return absl::Substitute(
        "  sapi::v::RemotePtr sapi_cb_$0(reinterpret_cast<void*>(\n"
        "      $1(reinterpret_cast<uintptr_t>($0))));\n",
        cb_param.name, RegisterCallbackName(*cb.typedef_name));
  }
  std::string idempotent_arg = cb.idempotent ? "" : ", /*idempotent=*/false";
  if (!NeedsCallbackLambdaWrapper(cb)) {
    return absl::Substitute(
        R"(  std::optional<sapi::v::Callback> sapi_cb_$0;
  if ($0) {
    sapi_cb_$0.emplace($0$1);
    sandbox->Check(sandbox->Allocate(&sapi_cb_$0.value(),
                                     /*automatic_free=*/true));
  }
)",
        cb_param.name, idempotent_arg);
  }

  std::string ret_vars;
  std::string cb_ret_type = GetCallbackReturnType(cb);
  bool is_ret_ptr = CallbackReturnsPointer(cb);
  if (is_ret_ptr) {
    absl::SubstituteAndAppend(&ret_vars,
                              "  std::vector<std::unique_ptr<sapi::v::Var>> "
                              "sapi_cb_ret_vars_$0;\n",
                              cb_param.name);
    if (cb.is_callback_return_aliased) {
      absl::SubstituteAndAppend(&ret_vars,
                                "  absl::flat_hash_map<uintptr_t, void*> "
                                "sapi_alias_cb_return_map_$0;\n",
                                cb_param.name);
    }
  }

  std::vector<std::string> lambda_params;
  std::vector<std::string> lambda_call_args;
  std::vector<std::string> pre_call_blocks;
  std::string param_sync_post_call;
  EmitCallbackParamMarshaling(cb.callback_parameters, lambda_params,
                              lambda_call_args, pre_call_blocks,
                              param_sync_post_call);

  std::string param_sync_pre_call;
  if (!pre_call_blocks.empty()) {
    param_sync_pre_call =
        absl::StrCat(absl::StrJoin(pre_call_blocks, "\n\n"), "\n\n");
  }

  std::string lambda_call_str = absl::StrJoin(lambda_call_args, ", ");
  std::string lambda_body;

  if (is_ret_ptr) {
    std::string ret_size_expr = GetCallbackReturnSizeAsBytesExpr(cb_param, cb);
    std::string alias_map_code;
    if (cb.is_callback_return_aliased) {
      alias_map_code = absl::Substitute(
          "      "
          "sapi_alias_cb_return_map_$0[reinterpret_cast<uintptr_t>(\n"
          "          sapi_ret_var->GetRemote())] = "
          "sapi_$0_ret_host;\n",
          cb_param.name);
    }
    std::string transfer_code;
    bool ret_uninitialized =
        cb.uninitialized ||
        (cb.return_value && cb.return_value->uninitialized());
    if (!ret_uninitialized) {
      transfer_code =
          "      "
          "sandbox->Check(sandbox->TransferToSandboxee(sapi_ret_var."
          "get()));\n";
    }
    std::string maybe_post_call =
        param_sync_post_call.empty() ? ""
                                     : absl::StrCat(param_sync_post_call, "\n");
    std::string ret_host_cast =
        (cb.return_value != nullptr &&
         cb.return_value->type.pointee != nullptr &&
         cb.return_value->type.pointee->is_const)
            ? absl::Substitute(
                  "const_cast<char*>(reinterpret_cast<const char*>("
                  "sapi_$0_ret_host))",
                  cb_param.name)
            : absl::Substitute("reinterpret_cast<char*>(sapi_$0_ret_host)",
                               cb_param.name);
    lambda_body = absl::Substitute(
        R"($0      // Forward params -> args, and do the callback
      $1 sapi_$2_ret_host = $2($3);
$7      // If the callback returned null, no need to
      // allocate a sandbox copy, sync, etc.
      if (!sapi_$2_ret_host) {
        return nullptr;
      }
      // Otherwise, make a sandbox copy of the
      // return value, and return the sandbox copy.

      size_t ret_size_bytes = $4;
      auto sapi_ret_var = std::make_unique<sapi::v::Array<char>>(
          $8, ret_size_bytes);
      sandbox->Check(sandbox->Allocate(sapi_ret_var.get(),
                                       /*automatic_free=*/true));
$5$6      auto ret_remote_ptr = sapi_ret_var->GetRemote();
      sapi_cb_ret_vars_$2.push_back(std::move(sapi_ret_var));
      return reinterpret_cast<$1>(ret_remote_ptr);
)",
        param_sync_pre_call, cb_ret_type, cb_param.name, lambda_call_str,
        ret_size_expr, transfer_code, alias_map_code, maybe_post_call,
        ret_host_cast);
  } else if (cb_ret_type == "void") {
    if (param_sync_post_call.empty()) {
      lambda_body = absl::Substitute(
          R"($0      // Forward params -> args, and do the callback
      $1($2);
)",
          param_sync_pre_call, cb_param.name, lambda_call_str);
    } else {
      lambda_body = absl::Substitute(
          R"($0      // Forward params -> args, and do the callback
      $1($2);

$3)",
          param_sync_pre_call, cb_param.name, lambda_call_str,
          param_sync_post_call);
    }
  } else {
    if (param_sync_post_call.empty()) {
      lambda_body = absl::Substitute(
          R"($0      // Forward params -> args, and do the callback
      $1 sapi_$2_ret = $2($3);
      return sapi_$2_ret;
)",
          param_sync_pre_call, cb_ret_type, cb_param.name, lambda_call_str);
    } else {
      lambda_body = absl::Substitute(
          R"($0      // Forward params -> args, and do the callback
      $1 sapi_$2_ret = $2($3);

$4      return sapi_$2_ret;
)",
          param_sync_pre_call, cb_ret_type, cb_param.name, lambda_call_str,
          param_sync_post_call);
    }
  }

  std::string lambda_params_str = absl::StrJoin(lambda_params, ", ");

  return absl::Substitute(
      R"(  std::optional<sapi::v::Callback> sapi_cb_$0;
  // Variables to track callback return values, etc.
$1  // If the callback is not null, set the sapi_cb var to a lambda.
  if ($0) {
    auto sapi_lambda_$0 = [&]($2) -> $3 {
$4    };
    sapi_cb_$0.emplace(sapi_lambda_$0$5);
    sandbox->Check(sandbox->Allocate(&sapi_cb_$0.value(),
                                     /*automatic_free=*/true));
  }
)",
      cb_param.name, ret_vars, lambda_params_str, cb_ret_type, lambda_body,
      idempotent_arg);
}


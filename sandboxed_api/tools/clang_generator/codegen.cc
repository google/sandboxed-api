// Emits pre-call memory allocation and data synchronization for struct pointer
// members annotated with SANDBOX_STRUCT_SYNC.
std::string EmitStructMemberSyncsPreCall(
    const ir::Parameter& param, const ir::StructSyncParam& sync_param) {
  std::string ret;
  for (const auto& sync : sync_param.members) {
    std::string member_terminal =
        sync.member_name.empty() ? sync.access_path() : sync.member_name;
    std::string suffix = absl::StrCat(param.name, "_", member_terminal);
    std::string host_ptr_expr = sync.access_path();

    std::string size_calc = std::visit(
        absl::Overload{
            [&](const ir::bounds::NullTerminated&) {
              return absl::Substitute(
                  "sapi_member_size_$0 = "
                  "strlen(reinterpret_cast<const char*>($1)) + 1;\n",
                  suffix, host_ptr_expr);
            },
            [&](const ir::bounds::SizedByBinding& binding) {
              std::string context_var =
                  ResolveContextName(binding.context_expr);
              std::string size_expr =
                  CompileBindingExpr(context_var, binding.binding_name);
              return absl::Substitute("sapi_member_size_$0 = $1;\n", suffix,
                                      size_expr);
            },
            [&](const ir::bounds::ByteCount& byte) {
              return absl::Substitute("sapi_member_size_$0 = $1$2;\n", suffix,
                                      sync.parent_prefix, byte.size_expr);
            },
            [&](const ir::bounds::ElemCount& elem) {
              return absl::Substitute(
                  "sapi_member_size_$0 = "
                  "sandbox->CheckedMultiply(sizeof(*($1)), ($2$3));\n",
                  suffix, host_ptr_expr, sync.parent_prefix, elem.size_expr);
            },
            [&](const auto& b) {
              using T = std::decay_t<decltype(b)>;
              static_assert(IsOneOf<T, ir::bounds::Singleton,
                                    ir::bounds::ElemSizedByOutparam,
                                    ir::bounds::ByteSizedByOutparam>,
                            "Unhandled struct member bounds in "
                            "EmitStructMemberSyncsPreCall!");
              return absl::Substitute("sapi_member_size_$0 = sizeof(*($1));\n",
                                      suffix, host_ptr_expr);
            },
        },
        sync.bounds);

    std::string copy_code;
    if (sync.direction == PointerDir::kIn ||
        sync.direction == PointerDir::kInOut) {
      copy_code = absl::Substitute(
          R"(sandbox->Check(
     sandbox->rpc_channel()
         ->CopyToSandbox(
             reinterpret_cast<uintptr_t>(sapi_sb_copy_$0),
             absl::MakeSpan(reinterpret_cast<const char*>($1),
                            sapi_member_size_$0))
         .status());
)",
          suffix, host_ptr_expr);
    }

    std::string update_host_to_sb_ptr_code = absl::Substitute(
        R"(sapi_tmp_$0.mutable_data()->$1 =
   reinterpret_cast<decltype(sapi_tmp_$0.mutable_data()->$1)>(
       sapi_sb_copy_$2);
)",
        param.name, member_terminal, suffix);

    absl::SubstituteAndAppend(&ret,
                              R"(  void* sapi_sb_copy_$0 = nullptr;
  size_t sapi_member_size_$0 = 0;
  if ($1 != nullptr && $2 != nullptr) {
    // Compute size
    $3
    // Allocate
    sandbox->Check(sandbox->rpc_channel()->Allocate(
        sapi_member_size_$0, &sapi_sb_copy_$0));
    // copy host to sb if needed
    $4
    // update ptr member (host to sb)
    $5
  }
)",
                              suffix, param.name, host_ptr_expr, size_calc,
                              copy_code, update_host_to_sb_ptr_code);
  }
  return ret;
}

// Emits post-call data synchronization from sandbox to host for struct pointer
// members, and either retains the remote pointer in ContextBindingRegistry or
// frees the temporary sandbox allocation.
std::string EmitStructMemberSyncsPostCall(
    const ir::Parameter& param, const ir::StructSyncParam& sync_param) {
  std::string out;
  for (const auto& sync : sync_param.members) {
    std::string member_terminal =
        sync.member_name.empty() ? sync.access_path() : sync.member_name;
    std::string suffix = absl::StrCat(param.name, "_", member_terminal);
    std::string host_ptr_expr = sync.access_path();

    if (sync.direction == PointerDir::kOut ||
        sync.direction == PointerDir::kInOut) {
      absl::SubstituteAndAppend(&out,
                                R"(  if (sapi_sb_copy_$0 != nullptr) {
    sapi::lwbox::SyncFromSandboxToHost(
        *sandbox, reinterpret_cast<uintptr_t>(sapi_sb_copy_$0),
        reinterpret_cast<void*>($1), sapi_member_size_$0);
  }
)",
                                suffix, host_ptr_expr);
    }
    if (sync.context_bound.retain_and_bind.has_value()) {
      std::string ctx_name =
          ResolveContextName(sync.context_bound.retain_and_bind->context);
      absl::SubstituteAndAppend(
          &out,
          R"(  if (sapi_sb_copy_$0 != nullptr && $1 != nullptr) {
    sapi::lwbox::ContextBindingRegistry::Instance()->RetainPointer(
        $1, "$2", reinterpret_cast<uintptr_t>(sapi_sb_copy_$0),
        sapi_member_size_$0);
  }
)",
          suffix, ctx_name, sync.context_bound.retain_and_bind->binding_name);
    } else {
      absl::SubstituteAndAppend(&out,
                                R"(  if (sapi_sb_copy_$0 != nullptr) {
    sandbox->Check(sandbox->rpc_channel()->Free(sapi_sb_copy_$0));
  }
)",
                                suffix);
    }
  }
  return out;
}

// Emits code to synchronize a returned or out-parameter pointer from the
// sandboxee, allocating a host buffer and caching/binding it in the
// ContextBindingRegistry. If already bound, synchronizes the existing host copy
// or re-binds if the remote sandbox pointer changed.
std::string EmitCopyFromAndBindOutPtrCode(
    const CopyFromAndBindOutPtr& cb, absl::string_view out_ptr_name,
    absl::string_view out_ptr_type, const ir::BufferBounds& buffer_bounds) {
  std::string ctx_name = ResolveContextName(cb.context);
  std::string size_calc;
  std::string alloc_and_copy_code;

  if (const auto* byte = std::get_if<ir::bounds::ByteCount>(&buffer_bounds)) {
    size_calc =
        absl::Substitute("size_t sapi_binding_size = $0;\n", byte->size_expr);
    alloc_and_copy_code = R"(
        sapi_host_copy = calloc(sapi_binding_size, sizeof(char));
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, sapi_sb_ptr, sapi_host_copy, sapi_binding_size);
)";
  } else if (const auto* elem =
                 std::get_if<ir::bounds::ElemCount>(&buffer_bounds)) {
    size_calc = absl::Substitute(
        "size_t sapi_binding_size = "
        "sandbox->CheckedMultiply(sizeof(*sapi_returned_sb_ptr), ($0));\n",
        elem->size_expr);
    alloc_and_copy_code = R"(
        sapi_host_copy = calloc(sapi_binding_size, sizeof(char));
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, sapi_sb_ptr, sapi_host_copy, sapi_binding_size);
)";
  } else if (std::holds_alternative<ir::bounds::NullTerminated>(
                 buffer_bounds)) {
    alloc_and_copy_code = R"(
        absl::StatusOr<std::string> sapi_remote_str =
            sandbox->GetCString(sapi::v::RemotePtr(
                reinterpret_cast<const void*>(sapi_sb_ptr)));
        sandbox->Check(sapi_remote_str.status());
        size_t sapi_binding_size = sapi_remote_str->size();
        sapi_host_copy = calloc(sapi_binding_size + 1, sizeof(char));
        memcpy(sapi_host_copy, sapi_remote_str->data(), sapi_binding_size);
)";
  } else if (const auto* binding =
                 std::get_if<ir::bounds::SizedByBinding>(&buffer_bounds)) {
    std::string context_var = ResolveContextName(binding->context_expr);
    std::string size_expr =
        CompileBindingExpr(context_var, binding->binding_name);
    size_calc = absl::Substitute("size_t sapi_binding_size = $0;\n", size_expr);
    alloc_and_copy_code = R"(
        sapi_host_copy = calloc(sapi_binding_size, sizeof(char));
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, sapi_sb_ptr, sapi_host_copy, sapi_binding_size);
)";
  }

  // The `else` branch below reuses the host buffer recorded when the binding
  // was first created, and syncs it using `sapi_bound_buf->bytes`, the size
  // captured at bind time. If the sandboxee has since grown the buffer, only
  // the original number of bytes is copied back and the host copy is stale.
  // TODO(b/491828958): Re-read the current size instead of reusing the size
  // captured at bind time.
  return absl::Substitute(
      R"(  {  // Get or create context binding.
    auto* sapi_returned_sb_ptr = $2.GetValue();
    if (sapi_returned_sb_ptr != nullptr && $0 != nullptr) {
      uintptr_t sapi_sb_ptr = reinterpret_cast<uintptr_t>(sapi_returned_sb_ptr);
      void* sapi_host_copy = nullptr;
      auto sapi_bound_buf =
          sapi::lwbox::ContextBindingRegistry::Instance()
              ->GetBoundHostBuffer($0, "$1");
      if (!sapi_bound_buf.has_value() ||
          sapi_bound_buf->remote_ptr != sapi_sb_ptr) {
        $3$4        sapi::lwbox::ContextBindingRegistry::Instance()
            ->BindHostBuffer($0, "$1", sapi_sb_ptr, sapi_host_copy,
                             sapi_binding_size);
      } else {
        sapi_host_copy = sapi_bound_buf->host_ptr;
        sapi::lwbox::SyncFromSandboxToHost(
            *sandbox, sapi_sb_ptr, sapi_host_copy, sapi_bound_buf->bytes);
      }
      $2.SetValue(reinterpret_cast<$5>(sapi_host_copy));
    }
  }
)",
      ctx_name, cb.binding_name, out_ptr_name, size_calc, alloc_and_copy_code,
      out_ptr_type);
}

